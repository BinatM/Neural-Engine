module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0110011000101111;
		 mem[1] = 16'b0000011001110011;
		 mem[2] = 16'b1100010000110000;
		 mem[3] = 16'b1110111111111100;
		 mem[4] = 16'b1100111011000011;
		 mem[5] = 16'b0110011001100001;
		 mem[6] = 16'b1111011001101101;
		 mem[7] = 16'b0001100011010101;
		 mem[8] = 16'b0010011100001100;
		 mem[9] = 16'b1000011110011000;
		 mem[10] = 16'b1101110110000100;
		 mem[11] = 16'b0100010000100001;
		 mem[12] = 16'b1011011110110111;
		 mem[13] = 16'b0000010000010001;
		 mem[14] = 16'b1010001110001110;
		 mem[15] = 16'b1101111010001001;
		 mem[16] = 16'b1001010001001010;
		 mem[17] = 16'b0111111010000100;
		 mem[18] = 16'b0100100010011010;
		 mem[19] = 16'b0101110011001110;
		 mem[20] = 16'b1111011000000001;
		 mem[21] = 16'b1100010101010001;
		 mem[22] = 16'b0100110000110011;
		 mem[23] = 16'b1110110001100111;
		 mem[24] = 16'b0110100111011001;
		 mem[25] = 16'b0000000011101000;
		 mem[26] = 16'b0111010011011110;
		 mem[27] = 16'b1011100000110101;
		 mem[28] = 16'b0100111000001011;
		 mem[29] = 16'b1100000011101011;
		 mem[30] = 16'b1001000001000000;
		 mem[31] = 16'b0011000111000100;
		 mem[32] = 16'b0001100100001100;
		 mem[33] = 16'b0101100100111001;
		 mem[34] = 16'b1111001010010001;
		 mem[35] = 16'b1101010010010100;
		 mem[36] = 16'b1100010001101010;
		 mem[37] = 16'b0010001000000110;
		 mem[38] = 16'b1011011101010010;
		 mem[39] = 16'b1110101011111111;
		 mem[40] = 16'b0111110111010110;
		 mem[41] = 16'b0100110000110010;
		 mem[42] = 16'b0001110100000011;
		 mem[43] = 16'b0100011100100111;
		 mem[44] = 16'b1101100100111110;
		 mem[45] = 16'b1100101110110000;
		 mem[46] = 16'b0100011101111011;
		 mem[47] = 16'b1111000000100111;
		 mem[48] = 16'b1011011101111001;
		 mem[49] = 16'b0000110011101010;
		 mem[50] = 16'b0011011011111110;
		 mem[51] = 16'b1100001001001110;
		 mem[52] = 16'b0001010011000001;
		 mem[53] = 16'b1111010010101000;
		 mem[54] = 16'b0100110110001101;
		 mem[55] = 16'b1001010110011011;
		 mem[56] = 16'b0010100000101010;
		 mem[57] = 16'b1010010000010001;
		 mem[58] = 16'b0001011100010110;
		 mem[59] = 16'b1111000101111001;
		 mem[60] = 16'b1101100000111100;
		 mem[61] = 16'b0110111100001101;
		 mem[62] = 16'b0001011000000110;
		 mem[63] = 16'b0110011011100101;
		 mem[64] = 16'b0001001000111011;
		 mem[65] = 16'b0000000000101011;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
