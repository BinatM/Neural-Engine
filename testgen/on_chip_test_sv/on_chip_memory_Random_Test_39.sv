module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0110101111000000;
		 mem[1] = 16'b0101111101010110;
		 mem[2] = 16'b0011011110011010;
		 mem[3] = 16'b0110100000100010;
		 mem[4] = 16'b1110111001101001;
		 mem[5] = 16'b0101010010110110;
		 mem[6] = 16'b0000110011010101;
		 mem[7] = 16'b0001000011011101;
		 mem[8] = 16'b1101110001001001;
		 mem[9] = 16'b0100100110101011;
		 mem[10] = 16'b1010101111111101;
		 mem[11] = 16'b0110011100010101;
		 mem[12] = 16'b1111101000001001;
		 mem[13] = 16'b0011010110011101;
		 mem[14] = 16'b0111011010001011;
		 mem[15] = 16'b0010111100010011;
		 mem[16] = 16'b0100001001110010;
		 mem[17] = 16'b0011110101111101;
		 mem[18] = 16'b0101100111010110;
		 mem[19] = 16'b0000010000111011;
		 mem[20] = 16'b1100010111000010;
		 mem[21] = 16'b1010100100011010;
		 mem[22] = 16'b0110000000110011;
		 mem[23] = 16'b1101010111100101;
		 mem[24] = 16'b0110101011101000;
		 mem[25] = 16'b0010000000101111;
		 mem[26] = 16'b1110010110110110;
		 mem[27] = 16'b1011011010101110;
		 mem[28] = 16'b0000111110010101;
		 mem[29] = 16'b1100000000110110;
		 mem[30] = 16'b1110010100001001;
		 mem[31] = 16'b0100000011110000;
		 mem[32] = 16'b0110100100010000;
		 mem[33] = 16'b1110100100101100;
		 mem[34] = 16'b1111010100011001;
		 mem[35] = 16'b0010110010011111;
		 mem[36] = 16'b0001111101111101;
		 mem[37] = 16'b1011101010100111;
		 mem[38] = 16'b0100000111111111;
		 mem[39] = 16'b0110111011100100;
		 mem[40] = 16'b1111110110101101;
		 mem[41] = 16'b1000100111110111;
		 mem[42] = 16'b1100000001100100;
		 mem[43] = 16'b1000000110000010;
		 mem[44] = 16'b0111100101011010;
		 mem[45] = 16'b0100011111101100;
		 mem[46] = 16'b0101111101100111;
		 mem[47] = 16'b0101011011000001;
		 mem[48] = 16'b1010000010010001;
		 mem[49] = 16'b0110011111111100;
		 mem[50] = 16'b1110101001100011;
		 mem[51] = 16'b0001011101000111;
		 mem[52] = 16'b0011100111110011;
		 mem[53] = 16'b1011101000001010;
		 mem[54] = 16'b0100000110011100;
		 mem[55] = 16'b1111101110101110;
		 mem[56] = 16'b1101100011000111;
		 mem[57] = 16'b0100100101001111;
		 mem[58] = 16'b0010100100100011;
		 mem[59] = 16'b1111001101001000;
		 mem[60] = 16'b0001100011011100;
		 mem[61] = 16'b1110010100001110;
		 mem[62] = 16'b0001011011111000;
		 mem[63] = 16'b0101111100100001;
		 mem[64] = 16'b1100010010100011;
		 mem[65] = 16'b0000000000100001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
