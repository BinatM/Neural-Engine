module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0001101100000111;
		 mem[1] = 16'b1111000010001000;
		 mem[2] = 16'b0001110011001011;
		 mem[3] = 16'b0011100000110100;
		 mem[4] = 16'b1011010000101001;
		 mem[5] = 16'b1011010100100010;
		 mem[6] = 16'b0111100101111100;
		 mem[7] = 16'b0110010111011101;
		 mem[8] = 16'b0110001101101011;
		 mem[9] = 16'b1000001011101011;
		 mem[10] = 16'b0000000011001100;
		 mem[11] = 16'b0110011011001110;
		 mem[12] = 16'b1011011100110011;
		 mem[13] = 16'b1101000111000110;
		 mem[14] = 16'b0101010111111110;
		 mem[15] = 16'b1011001010110111;
		 mem[16] = 16'b1111111011111101;
		 mem[17] = 16'b1011111100100110;
		 mem[18] = 16'b1000110010010100;
		 mem[19] = 16'b0000001001010011;
		 mem[20] = 16'b1010011010111101;
		 mem[21] = 16'b0101010111011110;
		 mem[22] = 16'b1111101001010101;
		 mem[23] = 16'b0101010101101100;
		 mem[24] = 16'b1111111001110010;
		 mem[25] = 16'b1110010000001111;
		 mem[26] = 16'b1101010110011001;
		 mem[27] = 16'b1101111101011000;
		 mem[28] = 16'b0110000110100010;
		 mem[29] = 16'b1110111000111111;
		 mem[30] = 16'b0000100011000001;
		 mem[31] = 16'b0111100111111101;
		 mem[32] = 16'b0100111010110010;
		 mem[33] = 16'b0010011100111010;
		 mem[34] = 16'b0101110101110000;
		 mem[35] = 16'b0011011110110111;
		 mem[36] = 16'b0000101100110011;
		 mem[37] = 16'b1010110001011011;
		 mem[38] = 16'b1101111100011110;
		 mem[39] = 16'b1111101000101000;
		 mem[40] = 16'b0001101100111010;
		 mem[41] = 16'b1000111110110001;
		 mem[42] = 16'b1100101100011111;
		 mem[43] = 16'b0000100011000110;
		 mem[44] = 16'b0000000000110010;
		 mem[45] = 16'b0101000110000000;
		 mem[46] = 16'b0100101101100110;
		 mem[47] = 16'b0010010100010101;
		 mem[48] = 16'b0100100100100100;
		 mem[49] = 16'b0111010010011010;
		 mem[50] = 16'b1000010101001110;
		 mem[51] = 16'b1001000100001000;
		 mem[52] = 16'b0011100010101110;
		 mem[53] = 16'b0101001101110100;
		 mem[54] = 16'b0001001111111101;
		 mem[55] = 16'b1111110001010101;
		 mem[56] = 16'b1010000010110010;
		 mem[57] = 16'b0110101101001101;
		 mem[58] = 16'b1001101001110110;
		 mem[59] = 16'b1011011100101100;
		 mem[60] = 16'b0001011111100100;
		 mem[61] = 16'b1100011110100101;
		 mem[62] = 16'b1010010010001001;
		 mem[63] = 16'b0101001110011101;
		 mem[64] = 16'b1101010100010010;
		 mem[65] = 16'b0000000000101101;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
