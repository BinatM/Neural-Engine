module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1101011001000110;
		 mem[1] = 16'b0000001111100001;
		 mem[2] = 16'b0110100000000111;
		 mem[3] = 16'b1011000010111100;
		 mem[4] = 16'b1100111101100010;
		 mem[5] = 16'b0111010010011000;
		 mem[6] = 16'b1000100010100011;
		 mem[7] = 16'b1111100111001001;
		 mem[8] = 16'b0110100001110001;
		 mem[9] = 16'b0010010001101001;
		 mem[10] = 16'b0100010100010000;
		 mem[11] = 16'b1000100011110110;
		 mem[12] = 16'b1001010100100111;
		 mem[13] = 16'b0010100111001010;
		 mem[14] = 16'b1110000001000101;
		 mem[15] = 16'b0011011110010000;
		 mem[16] = 16'b1101010111110010;
		 mem[17] = 16'b1100101000000000;
		 mem[18] = 16'b0011000000111010;
		 mem[19] = 16'b1100111000000110;
		 mem[20] = 16'b0101000100011001;
		 mem[21] = 16'b0111100111001110;
		 mem[22] = 16'b0001110110111101;
		 mem[23] = 16'b0110011010111000;
		 mem[24] = 16'b1100011000001101;
		 mem[25] = 16'b1101101100001011;
		 mem[26] = 16'b1001111011111000;
		 mem[27] = 16'b0001100000100101;
		 mem[28] = 16'b1000011101011110;
		 mem[29] = 16'b1101011110100100;
		 mem[30] = 16'b0101111111101011;
		 mem[31] = 16'b0100000001101000;
		 mem[32] = 16'b0010111011010010;
		 mem[33] = 16'b0101001111111101;
		 mem[34] = 16'b0001010110111101;
		 mem[35] = 16'b1011111100110110;
		 mem[36] = 16'b1011101010101111;
		 mem[37] = 16'b1001011011011110;
		 mem[38] = 16'b0110111010000011;
		 mem[39] = 16'b0111010100011100;
		 mem[40] = 16'b1110110000000110;
		 mem[41] = 16'b0011101000110100;
		 mem[42] = 16'b0000100100001000;
		 mem[43] = 16'b1101001011110000;
		 mem[44] = 16'b1000111000100101;
		 mem[45] = 16'b1011111100111110;
		 mem[46] = 16'b0000110101101100;
		 mem[47] = 16'b0011010000000100;
		 mem[48] = 16'b1001001101111111;
		 mem[49] = 16'b0001000101100111;
		 mem[50] = 16'b0110100011010101;
		 mem[51] = 16'b1110001101010110;
		 mem[52] = 16'b0101001000100110;
		 mem[53] = 16'b0110110011000111;
		 mem[54] = 16'b1000111010110101;
		 mem[55] = 16'b0001110100001000;
		 mem[56] = 16'b1110111101000100;
		 mem[57] = 16'b1110001011010101;
		 mem[58] = 16'b0101100000001101;
		 mem[59] = 16'b1101100011110100;
		 mem[60] = 16'b1011011011011111;
		 mem[61] = 16'b0001100101101111;
		 mem[62] = 16'b1100100101101100;
		 mem[63] = 16'b0100101101100011;
		 mem[64] = 16'b0101111000100100;
		 mem[65] = 16'b0000000000001111;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
