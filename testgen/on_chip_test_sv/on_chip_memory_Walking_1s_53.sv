    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0000000000000000;
		 mem[1] = 16'b0000000000000000;
		 mem[2] = 16'b0000000000000000;
		 mem[3] = 16'b0000000000000000;
		 mem[4] = 16'b0000000000000000;
