		 mem[48] = 16'b0000000000000000;
		 mem[49] = 16'b0000000000000000;
		 mem[50] = 16'b0000000000000000;
		 mem[51] = 16'b0000000000000000;
		 mem[52] = 16'b0000000000000000;
		 mem[53] = 16'b0000000100000001;
