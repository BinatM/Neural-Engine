module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0100001111110001;
		 mem[1] = 16'b0101001010000111;
		 mem[2] = 16'b1111110110110110;
		 mem[3] = 16'b0111011010100110;
		 mem[4] = 16'b1001110001010110;
		 mem[5] = 16'b1111010111000101;
		 mem[6] = 16'b0000100110011110;
		 mem[7] = 16'b0100010101110001;
		 mem[8] = 16'b0110011000001000;
		 mem[9] = 16'b1110001111000100;
		 mem[10] = 16'b0110000100000110;
		 mem[11] = 16'b1110100011001010;
		 mem[12] = 16'b1110111000000011;
		 mem[13] = 16'b0000011101001100;
		 mem[14] = 16'b1010110010010101;
		 mem[15] = 16'b1100111110010000;
		 mem[16] = 16'b0000101010011110;
		 mem[17] = 16'b0100000100001111;
		 mem[18] = 16'b0011011100000001;
		 mem[19] = 16'b1101101010110111;
		 mem[20] = 16'b0010010010101111;
		 mem[21] = 16'b1101000101100010;
		 mem[22] = 16'b1011011000001100;
		 mem[23] = 16'b1011100010001000;
		 mem[24] = 16'b0100000011011101;
		 mem[25] = 16'b0011011001011110;
		 mem[26] = 16'b1111101010001110;
		 mem[27] = 16'b0010101000101100;
		 mem[28] = 16'b1000111100010110;
		 mem[29] = 16'b0001010110000011;
		 mem[30] = 16'b0100000101100000;
		 mem[31] = 16'b0000110001011101;
		 mem[32] = 16'b0010010111000100;
		 mem[33] = 16'b0010000110111010;
		 mem[34] = 16'b0111110000101001;
		 mem[35] = 16'b0101101111001101;
		 mem[36] = 16'b1001101001111110;
		 mem[37] = 16'b0111010111110010;
		 mem[38] = 16'b0000001110111000;
		 mem[39] = 16'b1011110000001011;
		 mem[40] = 16'b0111100100101010;
		 mem[41] = 16'b1001000010100011;
		 mem[42] = 16'b1101000101001110;
		 mem[43] = 16'b0000001110110100;
		 mem[44] = 16'b1100111010011001;
		 mem[45] = 16'b1100001101110010;
		 mem[46] = 16'b0111111101001000;
		 mem[47] = 16'b1110001101100000;
		 mem[48] = 16'b0001010000101001;
		 mem[49] = 16'b1100010000110000;
		 mem[50] = 16'b0111101011110111;
		 mem[51] = 16'b0000010110010000;
		 mem[52] = 16'b0110011100011011;
		 mem[53] = 16'b1111001010111111;
		 mem[54] = 16'b1111001000110111;
		 mem[55] = 16'b1011001111010110;
		 mem[56] = 16'b1110100101010101;
		 mem[57] = 16'b0000100010110111;
		 mem[58] = 16'b1011101000001100;
		 mem[59] = 16'b0111111101011110;
		 mem[60] = 16'b0010110010000110;
		 mem[61] = 16'b0101100111001011;
		 mem[62] = 16'b1010011110010100;
		 mem[63] = 16'b0011110001001111;
		 mem[64] = 16'b0010110111100110;
		 mem[65] = 16'b0000000000100110;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
