module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1110110111100100;
		 mem[1] = 16'b1111010101011100;
		 mem[2] = 16'b1011110011010110;
		 mem[3] = 16'b1010010001010001;
		 mem[4] = 16'b1001111101110010;
		 mem[5] = 16'b0011001101010111;
		 mem[6] = 16'b1100011000000110;
		 mem[7] = 16'b1101011010100010;
		 mem[8] = 16'b0110010110111010;
		 mem[9] = 16'b1111011001001010;
		 mem[10] = 16'b0011110100101001;
		 mem[11] = 16'b0110011010010001;
		 mem[12] = 16'b0001111010111000;
		 mem[13] = 16'b1101001111111000;
		 mem[14] = 16'b1011011011111010;
		 mem[15] = 16'b0011111110110101;
		 mem[16] = 16'b1010001111110100;
		 mem[17] = 16'b0010000110100111;
		 mem[18] = 16'b1000000101000111;
		 mem[19] = 16'b0000110100111011;
		 mem[20] = 16'b0101111100101011;
		 mem[21] = 16'b0100110000100101;
		 mem[22] = 16'b1000010000011001;
		 mem[23] = 16'b1100100011010011;
		 mem[24] = 16'b1101111101111101;
		 mem[25] = 16'b0011100101111100;
		 mem[26] = 16'b0001000001011100;
		 mem[27] = 16'b0101010000111100;
		 mem[28] = 16'b0001101100011111;
		 mem[29] = 16'b0110001110111011;
		 mem[30] = 16'b1101110001100100;
		 mem[31] = 16'b0000110001110000;
		 mem[32] = 16'b1111101110100101;
		 mem[33] = 16'b1100110011101001;
		 mem[34] = 16'b0101111101101111;
		 mem[35] = 16'b0001000101010100;
		 mem[36] = 16'b0101010101010001;
		 mem[37] = 16'b0100010110000111;
		 mem[38] = 16'b1000011101011011;
		 mem[39] = 16'b0101000101001100;
		 mem[40] = 16'b0010110000111101;
		 mem[41] = 16'b1100111100100000;
		 mem[42] = 16'b1110011101101101;
		 mem[43] = 16'b1000100010011111;
		 mem[44] = 16'b1110101011111100;
		 mem[45] = 16'b1100110010101100;
		 mem[46] = 16'b0001111010011100;
		 mem[47] = 16'b0100010000010110;
		 mem[48] = 16'b1000001100101000;
		 mem[49] = 16'b0110101001011001;
		 mem[50] = 16'b1011111111000001;
		 mem[51] = 16'b0011111100000000;
		 mem[52] = 16'b1010111000111010;
		 mem[53] = 16'b0011111011001011;
		 mem[54] = 16'b1000111100011110;
		 mem[55] = 16'b1010110101110110;
		 mem[56] = 16'b0101101001011100;
		 mem[57] = 16'b1111001111101101;
		 mem[58] = 16'b1011000001000000;
		 mem[59] = 16'b0010111111101011;
		 mem[60] = 16'b1001110011001100;
		 mem[61] = 16'b0011111110001101;
		 mem[62] = 16'b0101101000000001;
		 mem[63] = 16'b1111001110010010;
		 mem[64] = 16'b0100000011111100;
		 mem[65] = 16'b0000000000010001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
