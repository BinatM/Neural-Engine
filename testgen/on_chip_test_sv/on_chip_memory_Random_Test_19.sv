module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1100010000100100;
		 mem[1] = 16'b1000010001110100;
		 mem[2] = 16'b1001100001001010;
		 mem[3] = 16'b0000001010001010;
		 mem[4] = 16'b0111110110001011;
		 mem[5] = 16'b0001000110000000;
		 mem[6] = 16'b0001000111010000;
		 mem[7] = 16'b0011100010010011;
		 mem[8] = 16'b1011110110000111;
		 mem[9] = 16'b1101010110010111;
		 mem[10] = 16'b1101011001111101;
		 mem[11] = 16'b0010111110101110;
		 mem[12] = 16'b0011100011111000;
		 mem[13] = 16'b0111010000000100;
		 mem[14] = 16'b1010111010011100;
		 mem[15] = 16'b1000110111101000;
		 mem[16] = 16'b0010101001000010;
		 mem[17] = 16'b1111011000001001;
		 mem[18] = 16'b0000110000100100;
		 mem[19] = 16'b0100010101100001;
		 mem[20] = 16'b1010110110111100;
		 mem[21] = 16'b1110011100010100;
		 mem[22] = 16'b1101110100011000;
		 mem[23] = 16'b1001000110101011;
		 mem[24] = 16'b0010101010110110;
		 mem[25] = 16'b0001000100001000;
		 mem[26] = 16'b1100101100110100;
		 mem[27] = 16'b0110001011010100;
		 mem[28] = 16'b1011010100100010;
		 mem[29] = 16'b0100000010101010;
		 mem[30] = 16'b0000101101001011;
		 mem[31] = 16'b0101001001011111;
		 mem[32] = 16'b1110100011110111;
		 mem[33] = 16'b1010111110100100;
		 mem[34] = 16'b0000100010000101;
		 mem[35] = 16'b0110011011010110;
		 mem[36] = 16'b0101000100111111;
		 mem[37] = 16'b1000001111000011;
		 mem[38] = 16'b0000100010110010;
		 mem[39] = 16'b1011011010010110;
		 mem[40] = 16'b1000011100111011;
		 mem[41] = 16'b1010100010101111;
		 mem[42] = 16'b0110011111101110;
		 mem[43] = 16'b0100011101111111;
		 mem[44] = 16'b1100011110101110;
		 mem[45] = 16'b0100110000001010;
		 mem[46] = 16'b1000010011100101;
		 mem[47] = 16'b0111111111100010;
		 mem[48] = 16'b0011100111111101;
		 mem[49] = 16'b1111100110100100;
		 mem[50] = 16'b0100010110001001;
		 mem[51] = 16'b0010011101001011;
		 mem[52] = 16'b0011110110010011;
		 mem[53] = 16'b1100111110101111;
		 mem[54] = 16'b0110110010011100;
		 mem[55] = 16'b1100010111001001;
		 mem[56] = 16'b0110011001111101;
		 mem[57] = 16'b1101001000010001;
		 mem[58] = 16'b1101101011100110;
		 mem[59] = 16'b1011010010111010;
		 mem[60] = 16'b1010110001100111;
		 mem[61] = 16'b0001001100010001;
		 mem[62] = 16'b0110010100011110;
		 mem[63] = 16'b0011100001111111;
		 mem[64] = 16'b0000011100101010;
		 mem[65] = 16'b0000000000101000;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
