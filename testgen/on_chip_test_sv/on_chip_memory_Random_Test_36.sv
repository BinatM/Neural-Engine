module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0100000010001100;
		 mem[1] = 16'b1111000011010000;
		 mem[2] = 16'b0110001110100110;
		 mem[3] = 16'b1100101000011111;
		 mem[4] = 16'b1010000111111011;
		 mem[5] = 16'b0010010101010010;
		 mem[6] = 16'b1010100101011110;
		 mem[7] = 16'b0000101100001111;
		 mem[8] = 16'b1101100000011011;
		 mem[9] = 16'b1110110001001010;
		 mem[10] = 16'b1000111111111010;
		 mem[11] = 16'b1010111000110111;
		 mem[12] = 16'b0101100110101011;
		 mem[13] = 16'b1010010000110100;
		 mem[14] = 16'b0010111111110100;
		 mem[15] = 16'b1100111010001001;
		 mem[16] = 16'b1011110000101010;
		 mem[17] = 16'b1010111010110111;
		 mem[18] = 16'b1011111110100101;
		 mem[19] = 16'b1010011011100001;
		 mem[20] = 16'b1110111101000101;
		 mem[21] = 16'b1101111101110001;
		 mem[22] = 16'b1110111010011001;
		 mem[23] = 16'b1011010010111000;
		 mem[24] = 16'b1011001011111110;
		 mem[25] = 16'b1000101000011110;
		 mem[26] = 16'b0010110011011111;
		 mem[27] = 16'b0000001100010000;
		 mem[28] = 16'b1011001101100001;
		 mem[29] = 16'b1010001010001011;
		 mem[30] = 16'b0100011111101101;
		 mem[31] = 16'b0111110011100101;
		 mem[32] = 16'b0011001100000011;
		 mem[33] = 16'b1101111011110101;
		 mem[34] = 16'b0000101111111010;
		 mem[35] = 16'b0110000010000110;
		 mem[36] = 16'b1110110110000101;
		 mem[37] = 16'b1101100111001100;
		 mem[38] = 16'b0101100010101101;
		 mem[39] = 16'b1001111000000001;
		 mem[40] = 16'b0010111101011100;
		 mem[41] = 16'b0100010001000000;
		 mem[42] = 16'b1001111101011110;
		 mem[43] = 16'b1010011011011010;
		 mem[44] = 16'b0011011001010000;
		 mem[45] = 16'b0011010100011000;
		 mem[46] = 16'b1101011111110000;
		 mem[47] = 16'b1110101101011011;
		 mem[48] = 16'b1010101100101010;
		 mem[49] = 16'b1111000000110011;
		 mem[50] = 16'b1101101010001010;
		 mem[51] = 16'b1100000001000011;
		 mem[52] = 16'b1011010111000000;
		 mem[53] = 16'b0001010101110000;
		 mem[54] = 16'b0011011011001010;
		 mem[55] = 16'b0110111000110110;
		 mem[56] = 16'b1011011000011100;
		 mem[57] = 16'b1010001101101000;
		 mem[58] = 16'b0101100110110100;
		 mem[59] = 16'b1000010100101000;
		 mem[60] = 16'b1000110001100001;
		 mem[61] = 16'b0110000111100101;
		 mem[62] = 16'b1101000111110110;
		 mem[63] = 16'b0101100110001010;
		 mem[64] = 16'b0100101101000011;
		 mem[65] = 16'b0000000000000010;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
