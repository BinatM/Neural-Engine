module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1011111101110001;
		 mem[1] = 16'b0011010011000001;
		 mem[2] = 16'b0001111011111111;
		 mem[3] = 16'b1001101001000111;
		 mem[4] = 16'b0011101101110111;
		 mem[5] = 16'b0010100100111110;
		 mem[6] = 16'b1100101111010010;
		 mem[7] = 16'b0111101111101101;
		 mem[8] = 16'b1010101111000101;
		 mem[9] = 16'b0111000000010111;
		 mem[10] = 16'b0010100111001000;
		 mem[11] = 16'b0001010010101101;
		 mem[12] = 16'b1001001011110110;
		 mem[13] = 16'b0111011010001001;
		 mem[14] = 16'b1100001100011010;
		 mem[15] = 16'b1111101010111100;
		 mem[16] = 16'b0111010100001011;
		 mem[17] = 16'b0001001000001000;
		 mem[18] = 16'b0001011011001011;
		 mem[19] = 16'b0000001101011110;
		 mem[20] = 16'b0110000111100100;
		 mem[21] = 16'b0011001101101000;
		 mem[22] = 16'b1101101010110101;
		 mem[23] = 16'b1000100100011111;
		 mem[24] = 16'b1001110011110001;
		 mem[25] = 16'b0101100000011110;
		 mem[26] = 16'b0101001011111011;
		 mem[27] = 16'b1011001010100001;
		 mem[28] = 16'b1011010010110111;
		 mem[29] = 16'b0110001001111101;
		 mem[30] = 16'b1100101000010110;
		 mem[31] = 16'b1100111000100010;
		 mem[32] = 16'b1111000101111100;
		 mem[33] = 16'b0100110110010001;
		 mem[34] = 16'b1001101110110000;
		 mem[35] = 16'b1100111000110100;
		 mem[36] = 16'b0000010101011111;
		 mem[37] = 16'b0011001010101000;
		 mem[38] = 16'b1111110101110100;
		 mem[39] = 16'b1001000011100111;
		 mem[40] = 16'b1001000111011100;
		 mem[41] = 16'b0100011111110010;
		 mem[42] = 16'b1111111110110101;
		 mem[43] = 16'b1110110110001110;
		 mem[44] = 16'b0110011101100011;
		 mem[45] = 16'b1010100110101101;
		 mem[46] = 16'b0111100000101010;
		 mem[47] = 16'b1010000111101110;
		 mem[48] = 16'b1010001100011100;
		 mem[49] = 16'b0011100011010010;
		 mem[50] = 16'b0010001110001010;
		 mem[51] = 16'b1010111101001101;
		 mem[52] = 16'b1010010001000101;
		 mem[53] = 16'b1010101100100011;
		 mem[54] = 16'b1001011111010101;
		 mem[55] = 16'b1011010001011000;
		 mem[56] = 16'b0001001110110101;
		 mem[57] = 16'b1001001101010101;
		 mem[58] = 16'b0000111001100011;
		 mem[59] = 16'b0101100110100001;
		 mem[60] = 16'b1000111001010110;
		 mem[61] = 16'b0000010100001101;
		 mem[62] = 16'b0101001001110000;
		 mem[63] = 16'b1110010001011101;
		 mem[64] = 16'b1111101000001000;
		 mem[65] = 16'b0000000000101111;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
