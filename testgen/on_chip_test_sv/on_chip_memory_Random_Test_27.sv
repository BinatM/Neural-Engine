module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1011001100010111;
		 mem[1] = 16'b0110101110011111;
		 mem[2] = 16'b0000100101001010;
		 mem[3] = 16'b1001110101001110;
		 mem[4] = 16'b1111010101000101;
		 mem[5] = 16'b1010011111011110;
		 mem[6] = 16'b1001111101001110;
		 mem[7] = 16'b0011011111111111;
		 mem[8] = 16'b1110101011111001;
		 mem[9] = 16'b0001011110101001;
		 mem[10] = 16'b1111100101110001;
		 mem[11] = 16'b0011000111100111;
		 mem[12] = 16'b0110010000110010;
		 mem[13] = 16'b1011001110110010;
		 mem[14] = 16'b0100011011111011;
		 mem[15] = 16'b0111110111001010;
		 mem[16] = 16'b1100111110011110;
		 mem[17] = 16'b1101000101011001;
		 mem[18] = 16'b1100000111110010;
		 mem[19] = 16'b0110000111110001;
		 mem[20] = 16'b0001110000000001;
		 mem[21] = 16'b0111110010001010;
		 mem[22] = 16'b0011100110100110;
		 mem[23] = 16'b1011100110111001;
		 mem[24] = 16'b0111110100100010;
		 mem[25] = 16'b0010100010100001;
		 mem[26] = 16'b0000000010101010;
		 mem[27] = 16'b0100111010000000;
		 mem[28] = 16'b0110101110111001;
		 mem[29] = 16'b1100100101110011;
		 mem[30] = 16'b1010101101011111;
		 mem[31] = 16'b1000101001100011;
		 mem[32] = 16'b0100000111110011;
		 mem[33] = 16'b0101000010101010;
		 mem[34] = 16'b0111110101000100;
		 mem[35] = 16'b1001010011000110;
		 mem[36] = 16'b1111100000100110;
		 mem[37] = 16'b1100111100111011;
		 mem[38] = 16'b0110101001110101;
		 mem[39] = 16'b1101100011100000;
		 mem[40] = 16'b0010000111110011;
		 mem[41] = 16'b1101110000001101;
		 mem[42] = 16'b1111001111101110;
		 mem[43] = 16'b0100111111010111;
		 mem[44] = 16'b1011110101000100;
		 mem[45] = 16'b0000010000111010;
		 mem[46] = 16'b1100000110011111;
		 mem[47] = 16'b0001010000110010;
		 mem[48] = 16'b0110100000110100;
		 mem[49] = 16'b0111101011001110;
		 mem[50] = 16'b0000001011011001;
		 mem[51] = 16'b1001001111011011;
		 mem[52] = 16'b0111011011110100;
		 mem[53] = 16'b0000000111101110;
		 mem[54] = 16'b0101110001111011;
		 mem[55] = 16'b1110110111000101;
		 mem[56] = 16'b1000011101010001;
		 mem[57] = 16'b1100101010000011;
		 mem[58] = 16'b1100101101100011;
		 mem[59] = 16'b1011010111100001;
		 mem[60] = 16'b0010101000111000;
		 mem[61] = 16'b1011111001010111;
		 mem[62] = 16'b0100101011010111;
		 mem[63] = 16'b1101001100100001;
		 mem[64] = 16'b0011100110001101;
		 mem[65] = 16'b0000000000101101;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
