module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0010110001110111;
		 mem[1] = 16'b0100001000110011;
		 mem[2] = 16'b0100111000100001;
		 mem[3] = 16'b1001000011111001;
		 mem[4] = 16'b0110011111001001;
		 mem[5] = 16'b1011010001011001;
		 mem[6] = 16'b0010011010111100;
		 mem[7] = 16'b0011100011011011;
		 mem[8] = 16'b0000100010101110;
		 mem[9] = 16'b1110010010011001;
		 mem[10] = 16'b0101111010111010;
		 mem[11] = 16'b1000101110100011;
		 mem[12] = 16'b0001100111010111;
		 mem[13] = 16'b0010110010101001;
		 mem[14] = 16'b0110100110100000;
		 mem[15] = 16'b0000111101001001;
		 mem[16] = 16'b0111000111010001;
		 mem[17] = 16'b1010001100001010;
		 mem[18] = 16'b1000001111011101;
		 mem[19] = 16'b1001010111110010;
		 mem[20] = 16'b0010101010010011;
		 mem[21] = 16'b0000111011101101;
		 mem[22] = 16'b1000000101100101;
		 mem[23] = 16'b1101010000100000;
		 mem[24] = 16'b1001110101000010;
		 mem[25] = 16'b1101001000010100;
		 mem[26] = 16'b0101011101010110;
		 mem[27] = 16'b1100100010011001;
		 mem[28] = 16'b0010111111001110;
		 mem[29] = 16'b0111111100100101;
		 mem[30] = 16'b0000110010110100;
		 mem[31] = 16'b1110010010111011;
		 mem[32] = 16'b1000001010111011;
		 mem[33] = 16'b0010010100110111;
		 mem[34] = 16'b0111110001000110;
		 mem[35] = 16'b1110010110101010;
		 mem[36] = 16'b1011001000101100;
		 mem[37] = 16'b1111010101010000;
		 mem[38] = 16'b0011000101111110;
		 mem[39] = 16'b1011011101000011;
		 mem[40] = 16'b0001110010111100;
		 mem[41] = 16'b1000110001001000;
		 mem[42] = 16'b1011100101110011;
		 mem[43] = 16'b0110100101111110;
		 mem[44] = 16'b1101010011101101;
		 mem[45] = 16'b0000110100010001;
		 mem[46] = 16'b0100111000000010;
		 mem[47] = 16'b0011100001010001;
		 mem[48] = 16'b0100011111111100;
		 mem[49] = 16'b0000011100101110;
		 mem[50] = 16'b1011100110000110;
		 mem[51] = 16'b0010010111000110;
		 mem[52] = 16'b1100101100000001;
		 mem[53] = 16'b0101111111011001;
		 mem[54] = 16'b0111001000110000;
		 mem[55] = 16'b1100111011110110;
		 mem[56] = 16'b0001101000111101;
		 mem[57] = 16'b0001101111100000;
		 mem[58] = 16'b0100001100100001;
		 mem[59] = 16'b1010000111110100;
		 mem[60] = 16'b1101001011100011;
		 mem[61] = 16'b1010101011000111;
		 mem[62] = 16'b0000001100001010;
		 mem[63] = 16'b1111111001001010;
		 mem[64] = 16'b1101000100101111;
		 mem[65] = 16'b0000000000101011;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
