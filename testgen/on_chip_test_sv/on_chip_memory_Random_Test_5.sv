module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1111100011011010;
		 mem[1] = 16'b0101011010001000;
		 mem[2] = 16'b1000101110111111;
		 mem[3] = 16'b0001001011001111;
		 mem[4] = 16'b1001001010011001;
		 mem[5] = 16'b0001101101101111;
		 mem[6] = 16'b1000100011010000;
		 mem[7] = 16'b1010000100000011;
		 mem[8] = 16'b0010001101110111;
		 mem[9] = 16'b1111011100010011;
		 mem[10] = 16'b1011101100000100;
		 mem[11] = 16'b1111000110001101;
		 mem[12] = 16'b1001010100100101;
		 mem[13] = 16'b1100111100001001;
		 mem[14] = 16'b0101001110001111;
		 mem[15] = 16'b1110100000000011;
		 mem[16] = 16'b0001001110010100;
		 mem[17] = 16'b0111110101101000;
		 mem[18] = 16'b0111011001010110;
		 mem[19] = 16'b0111110010000001;
		 mem[20] = 16'b1000011111100000;
		 mem[21] = 16'b1001000011001110;
		 mem[22] = 16'b0010000010111000;
		 mem[23] = 16'b1110101011100111;
		 mem[24] = 16'b0100010110111110;
		 mem[25] = 16'b1111110110001010;
		 mem[26] = 16'b0111000010001110;
		 mem[27] = 16'b1100110001010000;
		 mem[28] = 16'b1111011111011001;
		 mem[29] = 16'b0000000000001001;
		 mem[30] = 16'b1001101011111101;
		 mem[31] = 16'b0010010011111011;
		 mem[32] = 16'b1111011011101111;
		 mem[33] = 16'b1100111010110101;
		 mem[34] = 16'b0000000110111000;
		 mem[35] = 16'b1010100001010001;
		 mem[36] = 16'b0001011110100010;
		 mem[37] = 16'b1100010001001011;
		 mem[38] = 16'b1101010111000001;
		 mem[39] = 16'b0001110111000111;
		 mem[40] = 16'b1110011111011100;
		 mem[41] = 16'b1000000111001111;
		 mem[42] = 16'b0100101001010100;
		 mem[43] = 16'b1000000000000001;
		 mem[44] = 16'b0011001000111010;
		 mem[45] = 16'b1011010001110110;
		 mem[46] = 16'b1100100000111111;
		 mem[47] = 16'b0011111011101101;
		 mem[48] = 16'b1101011111010100;
		 mem[49] = 16'b0010011001001101;
		 mem[50] = 16'b1000001000011111;
		 mem[51] = 16'b1011010000011101;
		 mem[52] = 16'b0111101101100110;
		 mem[53] = 16'b1101101000000011;
		 mem[54] = 16'b1011101101001100;
		 mem[55] = 16'b0001101011000001;
		 mem[56] = 16'b0011000011010100;
		 mem[57] = 16'b0000111010001011;
		 mem[58] = 16'b0100111001001101;
		 mem[59] = 16'b0010001000010111;
		 mem[60] = 16'b0111111011000110;
		 mem[61] = 16'b0101010000010010;
		 mem[62] = 16'b0000101100110110;
		 mem[63] = 16'b1111010100000101;
		 mem[64] = 16'b1100101101000110;
		 mem[65] = 16'b0000000000111101;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
