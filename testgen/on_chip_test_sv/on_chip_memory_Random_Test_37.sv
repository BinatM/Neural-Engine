module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1100001000100010;
		 mem[1] = 16'b1110011101101111;
		 mem[2] = 16'b1101000011010010;
		 mem[3] = 16'b0101010110011111;
		 mem[4] = 16'b1001000001000111;
		 mem[5] = 16'b0001000101100100;
		 mem[6] = 16'b0101101100100111;
		 mem[7] = 16'b1010110001001011;
		 mem[8] = 16'b1110000101111110;
		 mem[9] = 16'b0000101110100111;
		 mem[10] = 16'b1011001000000110;
		 mem[11] = 16'b1011101010111010;
		 mem[12] = 16'b1000101010110111;
		 mem[13] = 16'b1101100101100001;
		 mem[14] = 16'b0101010100011101;
		 mem[15] = 16'b1110010111100111;
		 mem[16] = 16'b1000110100111111;
		 mem[17] = 16'b1101110010000100;
		 mem[18] = 16'b1110010111010010;
		 mem[19] = 16'b1101111001111101;
		 mem[20] = 16'b1010111100010110;
		 mem[21] = 16'b0000111101101011;
		 mem[22] = 16'b1101111110100101;
		 mem[23] = 16'b0101010010011001;
		 mem[24] = 16'b1010011100111000;
		 mem[25] = 16'b0000111100001111;
		 mem[26] = 16'b0101011110011101;
		 mem[27] = 16'b0101111011111100;
		 mem[28] = 16'b1000111111110100;
		 mem[29] = 16'b1011101010101010;
		 mem[30] = 16'b0111011110110000;
		 mem[31] = 16'b0011101100100011;
		 mem[32] = 16'b0011000011101011;
		 mem[33] = 16'b0000010001011001;
		 mem[34] = 16'b1101011100110111;
		 mem[35] = 16'b1101110000011011;
		 mem[36] = 16'b1011011100011000;
		 mem[37] = 16'b0001101101010100;
		 mem[38] = 16'b0011011100110010;
		 mem[39] = 16'b0001110100110110;
		 mem[40] = 16'b1001110010110001;
		 mem[41] = 16'b1000110101010101;
		 mem[42] = 16'b1100001000101110;
		 mem[43] = 16'b1100110110110011;
		 mem[44] = 16'b1010000110010101;
		 mem[45] = 16'b0101010101101011;
		 mem[46] = 16'b1001100100100010;
		 mem[47] = 16'b1010101011111001;
		 mem[48] = 16'b0000100100110000;
		 mem[49] = 16'b1000001010111100;
		 mem[50] = 16'b0111100101100011;
		 mem[51] = 16'b0100100100011000;
		 mem[52] = 16'b1001011110010100;
		 mem[53] = 16'b1101101001101100;
		 mem[54] = 16'b1110000111001111;
		 mem[55] = 16'b1101111000111000;
		 mem[56] = 16'b1000111011011000;
		 mem[57] = 16'b0110001011110010;
		 mem[58] = 16'b1101001111011111;
		 mem[59] = 16'b0011111001111000;
		 mem[60] = 16'b1000010111111111;
		 mem[61] = 16'b1100001101000100;
		 mem[62] = 16'b1001101011110000;
		 mem[63] = 16'b0011001011011010;
		 mem[64] = 16'b1000000011010111;
		 mem[65] = 16'b0000000000001000;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
