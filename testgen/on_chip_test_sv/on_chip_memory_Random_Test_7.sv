module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0010111111001110;
		 mem[1] = 16'b1101000110110100;
		 mem[2] = 16'b1010010000000001;
		 mem[3] = 16'b0111100111010011;
		 mem[4] = 16'b1111110011010001;
		 mem[5] = 16'b0110111111110011;
		 mem[6] = 16'b0001001001010110;
		 mem[7] = 16'b1000101000000111;
		 mem[8] = 16'b0110100101111100;
		 mem[9] = 16'b1010011110100110;
		 mem[10] = 16'b1010010010111101;
		 mem[11] = 16'b0000011010110001;
		 mem[12] = 16'b0011001100011000;
		 mem[13] = 16'b0010000110000100;
		 mem[14] = 16'b0010000110010010;
		 mem[15] = 16'b0101001111011001;
		 mem[16] = 16'b0010111101111000;
		 mem[17] = 16'b0100110001110011;
		 mem[18] = 16'b0101000011001000;
		 mem[19] = 16'b0100000111100011;
		 mem[20] = 16'b1111001011010100;
		 mem[21] = 16'b0110011110011110;
		 mem[22] = 16'b1001110110111001;
		 mem[23] = 16'b0111000101011010;
		 mem[24] = 16'b1010110011000101;
		 mem[25] = 16'b1110111001100101;
		 mem[26] = 16'b1010111111100011;
		 mem[27] = 16'b1100110110011100;
		 mem[28] = 16'b1011000100110100;
		 mem[29] = 16'b1111011100101000;
		 mem[30] = 16'b0000110100101001;
		 mem[31] = 16'b0111000010101011;
		 mem[32] = 16'b0111000100001000;
		 mem[33] = 16'b0011001110010010;
		 mem[34] = 16'b0000110000011011;
		 mem[35] = 16'b0010010111001110;
		 mem[36] = 16'b0110110011110100;
		 mem[37] = 16'b1000001001101001;
		 mem[38] = 16'b1011110100110001;
		 mem[39] = 16'b1010011110111100;
		 mem[40] = 16'b1111010101111110;
		 mem[41] = 16'b1111101101100001;
		 mem[42] = 16'b0010010101000111;
		 mem[43] = 16'b0010101000010001;
		 mem[44] = 16'b1100000001001000;
		 mem[45] = 16'b0111011101111100;
		 mem[46] = 16'b0010011101000000;
		 mem[47] = 16'b0011110111011000;
		 mem[48] = 16'b0111100001001111;
		 mem[49] = 16'b0000110001011110;
		 mem[50] = 16'b0111111001111111;
		 mem[51] = 16'b0101001110110001;
		 mem[52] = 16'b0101110100000100;
		 mem[53] = 16'b0110011010111011;
		 mem[54] = 16'b1000110111011011;
		 mem[55] = 16'b1101010110101111;
		 mem[56] = 16'b0110101011000111;
		 mem[57] = 16'b0000010011010110;
		 mem[58] = 16'b1001010010101111;
		 mem[59] = 16'b0011100010110010;
		 mem[60] = 16'b1011000111111011;
		 mem[61] = 16'b0101111111110001;
		 mem[62] = 16'b0001111100001110;
		 mem[63] = 16'b1000001010001110;
		 mem[64] = 16'b1000110000001100;
		 mem[65] = 16'b0000000000011011;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
