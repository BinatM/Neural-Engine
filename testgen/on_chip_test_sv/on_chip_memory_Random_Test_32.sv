module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0010011101010001;
		 mem[1] = 16'b1110101100000111;
		 mem[2] = 16'b1011110110001000;
		 mem[3] = 16'b0000111110111100;
		 mem[4] = 16'b0111101001111101;
		 mem[5] = 16'b1100011110100001;
		 mem[6] = 16'b0011001000100111;
		 mem[7] = 16'b1010000011011010;
		 mem[8] = 16'b0001000001110011;
		 mem[9] = 16'b1101111110001110;
		 mem[10] = 16'b1011100111000010;
		 mem[11] = 16'b1111000110101100;
		 mem[12] = 16'b1101110001011000;
		 mem[13] = 16'b0110110111010100;
		 mem[14] = 16'b0110101101000101;
		 mem[15] = 16'b0100011111111011;
		 mem[16] = 16'b1001100001100111;
		 mem[17] = 16'b0010010001101100;
		 mem[18] = 16'b0111100001111100;
		 mem[19] = 16'b0101110111111001;
		 mem[20] = 16'b1001111110000110;
		 mem[21] = 16'b1011001110101001;
		 mem[22] = 16'b0000111001100000;
		 mem[23] = 16'b1101000000011011;
		 mem[24] = 16'b1100111000100111;
		 mem[25] = 16'b1100110011111100;
		 mem[26] = 16'b1001110101100010;
		 mem[27] = 16'b1100011110110100;
		 mem[28] = 16'b1100111010101010;
		 mem[29] = 16'b1101001001100100;
		 mem[30] = 16'b1001011100011110;
		 mem[31] = 16'b0111001011111011;
		 mem[32] = 16'b1100001010000110;
		 mem[33] = 16'b1001010010010011;
		 mem[34] = 16'b1111000100111000;
		 mem[35] = 16'b1001010001111100;
		 mem[36] = 16'b1100110010101011;
		 mem[37] = 16'b1100101001101000;
		 mem[38] = 16'b0100100100110011;
		 mem[39] = 16'b1110110100010001;
		 mem[40] = 16'b0100100101011001;
		 mem[41] = 16'b1111100101110000;
		 mem[42] = 16'b0011011001011010;
		 mem[43] = 16'b1100100100101010;
		 mem[44] = 16'b0001100011010100;
		 mem[45] = 16'b1011100001001110;
		 mem[46] = 16'b1110100100010011;
		 mem[47] = 16'b0011110001000110;
		 mem[48] = 16'b0101101110011101;
		 mem[49] = 16'b1010100011011000;
		 mem[50] = 16'b0010101100011010;
		 mem[51] = 16'b0111010110000110;
		 mem[52] = 16'b0011110101000101;
		 mem[53] = 16'b0100001111110100;
		 mem[54] = 16'b0110010010001000;
		 mem[55] = 16'b1010001011010111;
		 mem[56] = 16'b1000001111100101;
		 mem[57] = 16'b1101111100101001;
		 mem[58] = 16'b0010000100111000;
		 mem[59] = 16'b0010010010001101;
		 mem[60] = 16'b0001010111110011;
		 mem[61] = 16'b1111011010010001;
		 mem[62] = 16'b1000110101001111;
		 mem[63] = 16'b0110101001111001;
		 mem[64] = 16'b1110110010011111;
		 mem[65] = 16'b0000000000000101;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
