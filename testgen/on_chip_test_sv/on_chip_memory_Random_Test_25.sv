module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1010111110001101;
		 mem[1] = 16'b1110101110111000;
		 mem[2] = 16'b0111010100100110;
		 mem[3] = 16'b1110101011001110;
		 mem[4] = 16'b0101100100101100;
		 mem[5] = 16'b0011010111101110;
		 mem[6] = 16'b1001011010001000;
		 mem[7] = 16'b1100001111110001;
		 mem[8] = 16'b0011100011101110;
		 mem[9] = 16'b0011111110001011;
		 mem[10] = 16'b0100110001010101;
		 mem[11] = 16'b1010111100111011;
		 mem[12] = 16'b1100000110000000;
		 mem[13] = 16'b1010010110100100;
		 mem[14] = 16'b1100000000100011;
		 mem[15] = 16'b1010110010101010;
		 mem[16] = 16'b1101100101101010;
		 mem[17] = 16'b1000001110110000;
		 mem[18] = 16'b1010100011111111;
		 mem[19] = 16'b0110110100111011;
		 mem[20] = 16'b1001001000100110;
		 mem[21] = 16'b1010110111110001;
		 mem[22] = 16'b1110100010001011;
		 mem[23] = 16'b0110011001101110;
		 mem[24] = 16'b0101100101100011;
		 mem[25] = 16'b1010001110010011;
		 mem[26] = 16'b0101101101100100;
		 mem[27] = 16'b1101011010001101;
		 mem[28] = 16'b1111001000100111;
		 mem[29] = 16'b0100001011100110;
		 mem[30] = 16'b1010101101001100;
		 mem[31] = 16'b0110101100101110;
		 mem[32] = 16'b0111101011111001;
		 mem[33] = 16'b0010000100101010;
		 mem[34] = 16'b1101101010011010;
		 mem[35] = 16'b0000111110111111;
		 mem[36] = 16'b1111100000111111;
		 mem[37] = 16'b1100001001011101;
		 mem[38] = 16'b1110110000011010;
		 mem[39] = 16'b0110011001100101;
		 mem[40] = 16'b0001101110110110;
		 mem[41] = 16'b1110111001010111;
		 mem[42] = 16'b1011000001010001;
		 mem[43] = 16'b1010101000000110;
		 mem[44] = 16'b0011010101100011;
		 mem[45] = 16'b1101101110111111;
		 mem[46] = 16'b1100100110111101;
		 mem[47] = 16'b0001011100011110;
		 mem[48] = 16'b0110000011101011;
		 mem[49] = 16'b0100010110110010;
		 mem[50] = 16'b1111111011110100;
		 mem[51] = 16'b0000111001011001;
		 mem[52] = 16'b0110011011011110;
		 mem[53] = 16'b1001100110111000;
		 mem[54] = 16'b1110101011001111;
		 mem[55] = 16'b0010010110101100;
		 mem[56] = 16'b0010100011110100;
		 mem[57] = 16'b1100100000100001;
		 mem[58] = 16'b1111111011100101;
		 mem[59] = 16'b0111011000001111;
		 mem[60] = 16'b0100101100001100;
		 mem[61] = 16'b1010001111111000;
		 mem[62] = 16'b0100100110100100;
		 mem[63] = 16'b0111100010011011;
		 mem[64] = 16'b0100011010001011;
		 mem[65] = 16'b0000000000011100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
