module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1111101100111001;
		 mem[1] = 16'b0000100111011001;
		 mem[2] = 16'b1110111001111011;
		 mem[3] = 16'b1010110000100101;
		 mem[4] = 16'b1110001001101000;
		 mem[5] = 16'b1010001100100101;
		 mem[6] = 16'b0001000011111001;
		 mem[7] = 16'b0111011100001011;
		 mem[8] = 16'b1001001111110100;
		 mem[9] = 16'b0101010000011011;
		 mem[10] = 16'b1111111111000011;
		 mem[11] = 16'b0100000000001110;
		 mem[12] = 16'b0001011011110001;
		 mem[13] = 16'b1000011000110011;
		 mem[14] = 16'b1101011110011000;
		 mem[15] = 16'b1000111111000111;
		 mem[16] = 16'b0111000111001000;
		 mem[17] = 16'b1100001111100101;
		 mem[18] = 16'b1011011100100111;
		 mem[19] = 16'b0100110100111111;
		 mem[20] = 16'b0011011101101111;
		 mem[21] = 16'b0011011001101101;
		 mem[22] = 16'b1101000011111100;
		 mem[23] = 16'b1110010111110111;
		 mem[24] = 16'b0011110010100110;
		 mem[25] = 16'b0111100000011111;
		 mem[26] = 16'b1000111101110101;
		 mem[27] = 16'b0111000110111011;
		 mem[28] = 16'b1100110000100110;
		 mem[29] = 16'b1101111110001110;
		 mem[30] = 16'b1000101110001111;
		 mem[31] = 16'b0101111111111011;
		 mem[32] = 16'b1101111101000001;
		 mem[33] = 16'b0011000110101000;
		 mem[34] = 16'b0110001010010000;
		 mem[35] = 16'b1000011100111101;
		 mem[36] = 16'b1011010110101001;
		 mem[37] = 16'b1111001101101101;
		 mem[38] = 16'b1010000101111000;
		 mem[39] = 16'b0111000000001101;
		 mem[40] = 16'b0010010001110110;
		 mem[41] = 16'b0001111100011001;
		 mem[42] = 16'b1011010101000111;
		 mem[43] = 16'b0110001001011101;
		 mem[44] = 16'b0011111101111011;
		 mem[45] = 16'b0000111010100000;
		 mem[46] = 16'b0000010110011111;
		 mem[47] = 16'b0111000110011100;
		 mem[48] = 16'b0011101010010000;
		 mem[49] = 16'b0100101111001001;
		 mem[50] = 16'b0000001001101111;
		 mem[51] = 16'b0011001011011100;
		 mem[52] = 16'b0110111111000110;
		 mem[53] = 16'b0111001111010001;
		 mem[54] = 16'b1101011000010111;
		 mem[55] = 16'b1000000010101111;
		 mem[56] = 16'b1101100110101101;
		 mem[57] = 16'b1000001110101101;
		 mem[58] = 16'b0010101111110011;
		 mem[59] = 16'b0001010101000110;
		 mem[60] = 16'b0001111111010110;
		 mem[61] = 16'b1101111000011000;
		 mem[62] = 16'b0101000001000101;
		 mem[63] = 16'b0110101000011010;
		 mem[64] = 16'b0011000110011010;
		 mem[65] = 16'b0000000000000001;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
