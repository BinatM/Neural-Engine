module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1100000011110101;
		 mem[1] = 16'b0011010000101000;
		 mem[2] = 16'b0100001101111101;
		 mem[3] = 16'b1101111011100111;
		 mem[4] = 16'b0001110100111110;
		 mem[5] = 16'b0011110110100101;
		 mem[6] = 16'b1100111111011001;
		 mem[7] = 16'b1010010110011111;
		 mem[8] = 16'b0011111011100111;
		 mem[9] = 16'b1010001110111001;
		 mem[10] = 16'b1101110011001011;
		 mem[11] = 16'b0000000010101000;
		 mem[12] = 16'b1001100100001110;
		 mem[13] = 16'b0110100101100000;
		 mem[14] = 16'b0011000111100110;
		 mem[15] = 16'b1100000111011001;
		 mem[16] = 16'b0111110111110101;
		 mem[17] = 16'b0001100100000010;
		 mem[18] = 16'b1111100111011110;
		 mem[19] = 16'b0111011000100110;
		 mem[20] = 16'b0111001000011011;
		 mem[21] = 16'b1111100000100001;
		 mem[22] = 16'b0100011100101000;
		 mem[23] = 16'b0111011111110100;
		 mem[24] = 16'b1011100010011100;
		 mem[25] = 16'b1100101000111001;
		 mem[26] = 16'b0001110100000100;
		 mem[27] = 16'b0111010100111101;
		 mem[28] = 16'b1011111101111011;
		 mem[29] = 16'b1011001001011100;
		 mem[30] = 16'b1011001111110111;
		 mem[31] = 16'b1101010000100101;
		 mem[32] = 16'b0000000001000111;
		 mem[33] = 16'b0101001001111010;
		 mem[34] = 16'b0110110101000110;
		 mem[35] = 16'b1111111000101001;
		 mem[36] = 16'b1011000001001101;
		 mem[37] = 16'b0110011010110111;
		 mem[38] = 16'b1010010111101000;
		 mem[39] = 16'b1000001010101000;
		 mem[40] = 16'b1011010110000000;
		 mem[41] = 16'b1101110101011100;
		 mem[42] = 16'b1011100000100111;
		 mem[43] = 16'b0110101101010011;
		 mem[44] = 16'b1011111000010001;
		 mem[45] = 16'b0110111011111110;
		 mem[46] = 16'b0000011000111010;
		 mem[47] = 16'b0000111001001111;
		 mem[48] = 16'b1001100110111100;
		 mem[49] = 16'b1111111010111111;
		 mem[50] = 16'b1011000001111001;
		 mem[51] = 16'b1000000011011100;
		 mem[52] = 16'b0110010010110110;
		 mem[53] = 16'b1110000011010111;
		 mem[54] = 16'b1100101010010010;
		 mem[55] = 16'b1100101000011100;
		 mem[56] = 16'b1101101111010001;
		 mem[57] = 16'b1100011001000101;
		 mem[58] = 16'b1010000010000010;
		 mem[59] = 16'b1010001100100111;
		 mem[60] = 16'b1100100110011001;
		 mem[61] = 16'b0000010011111110;
		 mem[62] = 16'b1100111010111010;
		 mem[63] = 16'b0110110001101011;
		 mem[64] = 16'b1011011000111010;
		 mem[65] = 16'b0000000000011101;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
