module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0110010000100011;
		 mem[1] = 16'b0000111010000110;
		 mem[2] = 16'b1010011010010010;
		 mem[3] = 16'b0011101000110010;
		 mem[4] = 16'b0010110001010001;
		 mem[5] = 16'b1000000000000111;
		 mem[6] = 16'b0011011111111000;
		 mem[7] = 16'b1101011100110101;
		 mem[8] = 16'b1111110010111110;
		 mem[9] = 16'b1010011111000111;
		 mem[10] = 16'b1111110100011001;
		 mem[11] = 16'b0111011101011000;
		 mem[12] = 16'b0010010111101111;
		 mem[13] = 16'b0001100101110000;
		 mem[14] = 16'b1110111011011000;
		 mem[15] = 16'b0001111111101111;
		 mem[16] = 16'b0101110101110110;
		 mem[17] = 16'b1100110000010001;
		 mem[18] = 16'b1010101001010111;
		 mem[19] = 16'b1101010010011101;
		 mem[20] = 16'b0111111010001011;
		 mem[21] = 16'b0101101001010011;
		 mem[22] = 16'b0000101000011001;
		 mem[23] = 16'b1011100000011011;
		 mem[24] = 16'b0001110001111111;
		 mem[25] = 16'b1010111001010110;
		 mem[26] = 16'b1001011011000110;
		 mem[27] = 16'b1111101011000000;
		 mem[28] = 16'b0000110011000111;
		 mem[29] = 16'b0111000010100110;
		 mem[30] = 16'b0110110001111010;
		 mem[31] = 16'b1111111101000100;
		 mem[32] = 16'b0111010011101110;
		 mem[33] = 16'b0100101000011110;
		 mem[34] = 16'b1110010010110110;
		 mem[35] = 16'b0100100000100100;
		 mem[36] = 16'b0001001001011100;
		 mem[37] = 16'b1101111100001011;
		 mem[38] = 16'b1111110111010001;
		 mem[39] = 16'b1001111111110110;
		 mem[40] = 16'b1001111100001110;
		 mem[41] = 16'b0111110000000101;
		 mem[42] = 16'b1000010110011001;
		 mem[43] = 16'b1101110101100110;
		 mem[44] = 16'b1010110110110111;
		 mem[45] = 16'b0110101010110111;
		 mem[46] = 16'b0100010011100100;
		 mem[47] = 16'b0101101110011011;
		 mem[48] = 16'b0000101100100000;
		 mem[49] = 16'b0101000000000111;
		 mem[50] = 16'b1001100010010011;
		 mem[51] = 16'b1110101000110111;
		 mem[52] = 16'b0010000100001011;
		 mem[53] = 16'b1000010000000100;
		 mem[54] = 16'b1110001010001000;
		 mem[55] = 16'b1101000111110110;
		 mem[56] = 16'b1100010000111000;
		 mem[57] = 16'b0111100101100101;
		 mem[58] = 16'b1111001000110110;
		 mem[59] = 16'b0011000000100011;
		 mem[60] = 16'b0110011011010101;
		 mem[61] = 16'b1100000110011110;
		 mem[62] = 16'b0000111010100011;
		 mem[63] = 16'b0000000011101011;
		 mem[64] = 16'b0100000001110100;
		 mem[65] = 16'b0000000000000100;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
