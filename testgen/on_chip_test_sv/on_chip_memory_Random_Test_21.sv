module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0000001000100100;
		 mem[1] = 16'b0111010100011110;
		 mem[2] = 16'b1000110101011100;
		 mem[3] = 16'b1111100000010100;
		 mem[4] = 16'b1101100111000110;
		 mem[5] = 16'b0110010111100001;
		 mem[6] = 16'b0100000110110010;
		 mem[7] = 16'b1010010111010011;
		 mem[8] = 16'b0111110100000100;
		 mem[9] = 16'b0100111101010011;
		 mem[10] = 16'b1010011010000101;
		 mem[11] = 16'b1111011100101110;
		 mem[12] = 16'b0010100001011101;
		 mem[13] = 16'b1010001000101010;
		 mem[14] = 16'b1111111101011101;
		 mem[15] = 16'b1011110010000000;
		 mem[16] = 16'b0000010110011100;
		 mem[17] = 16'b1010110010010011;
		 mem[18] = 16'b0110000100111001;
		 mem[19] = 16'b1001110100101111;
		 mem[20] = 16'b1111001101101110;
		 mem[21] = 16'b0010100011111100;
		 mem[22] = 16'b0100111100101001;
		 mem[23] = 16'b0110010011010111;
		 mem[24] = 16'b1000111101101100;
		 mem[25] = 16'b1011110010100110;
		 mem[26] = 16'b1011110101010000;
		 mem[27] = 16'b0101101101011000;
		 mem[28] = 16'b1010110010111000;
		 mem[29] = 16'b1011100010000011;
		 mem[30] = 16'b1101000101110010;
		 mem[31] = 16'b0110010111111110;
		 mem[32] = 16'b0111100110111101;
		 mem[33] = 16'b1010100111101100;
		 mem[34] = 16'b0011110000111001;
		 mem[35] = 16'b0001001010011010;
		 mem[36] = 16'b0001011110001101;
		 mem[37] = 16'b1010101000001100;
		 mem[38] = 16'b0001001001000010;
		 mem[39] = 16'b1100110110110010;
		 mem[40] = 16'b1101110111111000;
		 mem[41] = 16'b1000110000111111;
		 mem[42] = 16'b1100001011000110;
		 mem[43] = 16'b0011110001000010;
		 mem[44] = 16'b1101101010001010;
		 mem[45] = 16'b1010111010000001;
		 mem[46] = 16'b1111111000001001;
		 mem[47] = 16'b1111100010100111;
		 mem[48] = 16'b1110000100100101;
		 mem[49] = 16'b1111001010011101;
		 mem[50] = 16'b1010110011110000;
		 mem[51] = 16'b1011001111000111;
		 mem[52] = 16'b1110111110010111;
		 mem[53] = 16'b1011111010001110;
		 mem[54] = 16'b0000011100110001;
		 mem[55] = 16'b1011110000110100;
		 mem[56] = 16'b0101000001101111;
		 mem[57] = 16'b1100110101011111;
		 mem[58] = 16'b1000011101011010;
		 mem[59] = 16'b1100011011101001;
		 mem[60] = 16'b1001101110000000;
		 mem[61] = 16'b1101001000001010;
		 mem[62] = 16'b0100101001101001;
		 mem[63] = 16'b0010001101001101;
		 mem[64] = 16'b0001000110110001;
		 mem[65] = 16'b0000000000011000;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
