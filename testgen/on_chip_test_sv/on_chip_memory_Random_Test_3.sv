module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1000010011101110;
		 mem[1] = 16'b1000010110000011;
		 mem[2] = 16'b1111101000011100;
		 mem[3] = 16'b0010111011010001;
		 mem[4] = 16'b0011101101010010;
		 mem[5] = 16'b0100011010010010;
		 mem[6] = 16'b1110000010101111;
		 mem[7] = 16'b1010011101000001;
		 mem[8] = 16'b1001010010011110;
		 mem[9] = 16'b1011100011110000;
		 mem[10] = 16'b1100001101001001;
		 mem[11] = 16'b1100111010100000;
		 mem[12] = 16'b1011110110011010;
		 mem[13] = 16'b1010101000111111;
		 mem[14] = 16'b1001010000001001;
		 mem[15] = 16'b0110001010100111;
		 mem[16] = 16'b1001100100100010;
		 mem[17] = 16'b1111010101010010;
		 mem[18] = 16'b0100011010011011;
		 mem[19] = 16'b0101100111101000;
		 mem[20] = 16'b0000101011011010;
		 mem[21] = 16'b1000110110101111;
		 mem[22] = 16'b0001111110100011;
		 mem[23] = 16'b1011101001010011;
		 mem[24] = 16'b0000101101001111;
		 mem[25] = 16'b1010011001000111;
		 mem[26] = 16'b0010001011100111;
		 mem[27] = 16'b0101101010111110;
		 mem[28] = 16'b0100101000011000;
		 mem[29] = 16'b0001011000111110;
		 mem[30] = 16'b1111110010100110;
		 mem[31] = 16'b0010100110010001;
		 mem[32] = 16'b0110000110010010;
		 mem[33] = 16'b0001111110111111;
		 mem[34] = 16'b0010001100001110;
		 mem[35] = 16'b1001100111100101;
		 mem[36] = 16'b0101011001101100;
		 mem[37] = 16'b0000101010100000;
		 mem[38] = 16'b1001010100110010;
		 mem[39] = 16'b0100001101010111;
		 mem[40] = 16'b0110111111101011;
		 mem[41] = 16'b0001010100001110;
		 mem[42] = 16'b1001000001111000;
		 mem[43] = 16'b1010011100100001;
		 mem[44] = 16'b1011100111011111;
		 mem[45] = 16'b0001110010111100;
		 mem[46] = 16'b0101001001000011;
		 mem[47] = 16'b0101010100001110;
		 mem[48] = 16'b1100111010010100;
		 mem[49] = 16'b0000010110100010;
		 mem[50] = 16'b0010011010101010;
		 mem[51] = 16'b1110101110011001;
		 mem[52] = 16'b1001111111100111;
		 mem[53] = 16'b1110011111100111;
		 mem[54] = 16'b1000000110111111;
		 mem[55] = 16'b0011110011011010;
		 mem[56] = 16'b1011000111011010;
		 mem[57] = 16'b0000111001111111;
		 mem[58] = 16'b1111000000110011;
		 mem[59] = 16'b0010101110010100;
		 mem[60] = 16'b1010101011111000;
		 mem[61] = 16'b1111101111101101;
		 mem[62] = 16'b0101010100110100;
		 mem[63] = 16'b1101000100000101;
		 mem[64] = 16'b0111101101001001;
		 mem[65] = 16'b0000000000100001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
