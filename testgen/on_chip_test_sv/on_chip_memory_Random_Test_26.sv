module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1101111001101011;
		 mem[1] = 16'b1000111011010111;
		 mem[2] = 16'b0111010010111010;
		 mem[3] = 16'b1101100101001001;
		 mem[4] = 16'b0000100010000010;
		 mem[5] = 16'b1101001010010000;
		 mem[6] = 16'b0110001001111111;
		 mem[7] = 16'b1011101101011010;
		 mem[8] = 16'b1101001111001101;
		 mem[9] = 16'b0011010010111001;
		 mem[10] = 16'b1111011010110010;
		 mem[11] = 16'b0111000001010011;
		 mem[12] = 16'b1100101011110101;
		 mem[13] = 16'b0011101001001100;
		 mem[14] = 16'b0110110010011101;
		 mem[15] = 16'b0101111111011111;
		 mem[16] = 16'b0110000100000011;
		 mem[17] = 16'b0001010011111011;
		 mem[18] = 16'b0111100110111000;
		 mem[19] = 16'b1010100111000000;
		 mem[20] = 16'b0101000100011110;
		 mem[21] = 16'b0010011010010111;
		 mem[22] = 16'b0100101001001100;
		 mem[23] = 16'b1001110010010011;
		 mem[24] = 16'b0111101100110011;
		 mem[25] = 16'b0110010001001001;
		 mem[26] = 16'b0101010111010100;
		 mem[27] = 16'b1110011011011001;
		 mem[28] = 16'b1111100000111000;
		 mem[29] = 16'b1001100111110011;
		 mem[30] = 16'b0111101001000110;
		 mem[31] = 16'b1101010000001001;
		 mem[32] = 16'b0111100000010101;
		 mem[33] = 16'b0000110010100110;
		 mem[34] = 16'b1011000111110110;
		 mem[35] = 16'b0011010010010110;
		 mem[36] = 16'b0100011011111111;
		 mem[37] = 16'b0100000110100001;
		 mem[38] = 16'b1010011111100010;
		 mem[39] = 16'b1000000110010000;
		 mem[40] = 16'b0101101010001100;
		 mem[41] = 16'b0000000011101101;
		 mem[42] = 16'b1001100001100001;
		 mem[43] = 16'b1011001010000111;
		 mem[44] = 16'b1100111010011010;
		 mem[45] = 16'b0001110110111000;
		 mem[46] = 16'b1000100100000011;
		 mem[47] = 16'b0001001111100001;
		 mem[48] = 16'b0001100100101100;
		 mem[49] = 16'b1110101111101101;
		 mem[50] = 16'b0101011111110110;
		 mem[51] = 16'b1001010101001110;
		 mem[52] = 16'b0000001100000111;
		 mem[53] = 16'b1011010010111001;
		 mem[54] = 16'b1011110000010100;
		 mem[55] = 16'b1110100110100111;
		 mem[56] = 16'b1110001111000111;
		 mem[57] = 16'b0110011010000011;
		 mem[58] = 16'b1110000000011000;
		 mem[59] = 16'b1000100010100000;
		 mem[60] = 16'b1110100101110110;
		 mem[61] = 16'b1100111111101001;
		 mem[62] = 16'b0110010011011010;
		 mem[63] = 16'b0001110101000001;
		 mem[64] = 16'b1011111001011001;
		 mem[65] = 16'b0000000000000101;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
