module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1001010001110010;
		 mem[1] = 16'b0001111101011111;
		 mem[2] = 16'b0011001110001111;
		 mem[3] = 16'b0011101100111111;
		 mem[4] = 16'b1110101100000100;
		 mem[5] = 16'b1000101000001111;
		 mem[6] = 16'b0111101010101001;
		 mem[7] = 16'b1111001011001011;
		 mem[8] = 16'b1001110001111011;
		 mem[9] = 16'b0011100010000001;
		 mem[10] = 16'b0010101010110100;
		 mem[11] = 16'b1001000000111111;
		 mem[12] = 16'b1011100111011011;
		 mem[13] = 16'b1101110111101010;
		 mem[14] = 16'b1001001000011111;
		 mem[15] = 16'b0000111110100100;
		 mem[16] = 16'b0000011011010001;
		 mem[17] = 16'b1000100101000101;
		 mem[18] = 16'b1111001111010111;
		 mem[19] = 16'b0010000101010110;
		 mem[20] = 16'b0111000111010010;
		 mem[21] = 16'b0101011111111011;
		 mem[22] = 16'b1010000000000001;
		 mem[23] = 16'b0101110011001001;
		 mem[24] = 16'b1011001110000000;
		 mem[25] = 16'b0100110001101000;
		 mem[26] = 16'b0100001000100011;
		 mem[27] = 16'b0000111101000001;
		 mem[28] = 16'b0001001101001110;
		 mem[29] = 16'b1110100101110000;
		 mem[30] = 16'b0011010100111100;
		 mem[31] = 16'b0100100111010110;
		 mem[32] = 16'b1010111010011000;
		 mem[33] = 16'b0111000010110110;
		 mem[34] = 16'b1000111101100000;
		 mem[35] = 16'b0111111101101100;
		 mem[36] = 16'b0000001101101011;
		 mem[37] = 16'b1000100010010010;
		 mem[38] = 16'b0111011110001000;
		 mem[39] = 16'b1111011110010010;
		 mem[40] = 16'b0000010100110100;
		 mem[41] = 16'b0110101100111011;
		 mem[42] = 16'b0010100100101100;
		 mem[43] = 16'b0110100011011111;
		 mem[44] = 16'b1111111000011010;
		 mem[45] = 16'b0110000101010010;
		 mem[46] = 16'b0111010001011010;
		 mem[47] = 16'b1010110001011110;
		 mem[48] = 16'b1110101100011101;
		 mem[49] = 16'b0001110011001101;
		 mem[50] = 16'b0110111010001111;
		 mem[51] = 16'b1000100011111110;
		 mem[52] = 16'b0111001001011110;
		 mem[53] = 16'b0110011100101101;
		 mem[54] = 16'b0001011111000100;
		 mem[55] = 16'b0001110101110100;
		 mem[56] = 16'b1101110100110110;
		 mem[57] = 16'b0101111110110101;
		 mem[58] = 16'b1010100010101000;
		 mem[59] = 16'b1011111111010010;
		 mem[60] = 16'b1000100100111010;
		 mem[61] = 16'b0011001011110000;
		 mem[62] = 16'b0010111011011000;
		 mem[63] = 16'b1111110111011000;
		 mem[64] = 16'b1111011110101011;
		 mem[65] = 16'b0000000000110100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
