module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0111110101101010;
		 mem[1] = 16'b0010000011010110;
		 mem[2] = 16'b0000000101011110;
		 mem[3] = 16'b0000101101010000;
		 mem[4] = 16'b1101001011000010;
		 mem[5] = 16'b0000000111100101;
		 mem[6] = 16'b0100111100011110;
		 mem[7] = 16'b1100101010000011;
		 mem[8] = 16'b1001010011110010;
		 mem[9] = 16'b1101011111000011;
		 mem[10] = 16'b0011010000001110;
		 mem[11] = 16'b0100110011001111;
		 mem[12] = 16'b1001000100010110;
		 mem[13] = 16'b1000101111101110;
		 mem[14] = 16'b0010001001100101;
		 mem[15] = 16'b0101011011100110;
		 mem[16] = 16'b0100000010001011;
		 mem[17] = 16'b1111101101000101;
		 mem[18] = 16'b1111010011000010;
		 mem[19] = 16'b0101010101000001;
		 mem[20] = 16'b1000101001110100;
		 mem[21] = 16'b0101110100011001;
		 mem[22] = 16'b1110010101110000;
		 mem[23] = 16'b0110100111011010;
		 mem[24] = 16'b0100000111001010;
		 mem[25] = 16'b0110011100111001;
		 mem[26] = 16'b1101100101000110;
		 mem[27] = 16'b0110010011000010;
		 mem[28] = 16'b0100001011011001;
		 mem[29] = 16'b0111011100011100;
		 mem[30] = 16'b0101000101111101;
		 mem[31] = 16'b0100001101011101;
		 mem[32] = 16'b0100111111010101;
		 mem[33] = 16'b0101110000101011;
		 mem[34] = 16'b1100100011100001;
		 mem[35] = 16'b0010001010000101;
		 mem[36] = 16'b0001111101010011;
		 mem[37] = 16'b1000111100101001;
		 mem[38] = 16'b0100011100100101;
		 mem[39] = 16'b0110010111110111;
		 mem[40] = 16'b0111011001101100;
		 mem[41] = 16'b0011010010000101;
		 mem[42] = 16'b0101110011011010;
		 mem[43] = 16'b0110111110011010;
		 mem[44] = 16'b1110100000101110;
		 mem[45] = 16'b1011000000010000;
		 mem[46] = 16'b1010010110001110;
		 mem[47] = 16'b1001110001011100;
		 mem[48] = 16'b0010000001010110;
		 mem[49] = 16'b0000101100001111;
		 mem[50] = 16'b1110110101111100;
		 mem[51] = 16'b1011000000110011;
		 mem[52] = 16'b0000111101011010;
		 mem[53] = 16'b0011000111100111;
		 mem[54] = 16'b0110011010011110;
		 mem[55] = 16'b1100111010101110;
		 mem[56] = 16'b0111000100110100;
		 mem[57] = 16'b1101001000111111;
		 mem[58] = 16'b1101111001000111;
		 mem[59] = 16'b1001011010100000;
		 mem[60] = 16'b1100001110001000;
		 mem[61] = 16'b0010001101110111;
		 mem[62] = 16'b0001001100111100;
		 mem[63] = 16'b0000101011001100;
		 mem[64] = 16'b0111010110010001;
		 mem[65] = 16'b0000000000111000;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
