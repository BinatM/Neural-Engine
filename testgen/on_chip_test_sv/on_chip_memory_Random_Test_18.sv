module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0001110000100010;
		 mem[1] = 16'b1011101000010000;
		 mem[2] = 16'b1000100010011001;
		 mem[3] = 16'b0111100001001111;
		 mem[4] = 16'b0101011111111010;
		 mem[5] = 16'b1010000010100110;
		 mem[6] = 16'b0010011001111010;
		 mem[7] = 16'b0010001000000001;
		 mem[8] = 16'b0001111111011010;
		 mem[9] = 16'b0100000000001101;
		 mem[10] = 16'b0000000100110011;
		 mem[11] = 16'b0010000111010100;
		 mem[12] = 16'b0100100000111011;
		 mem[13] = 16'b1011101011110000;
		 mem[14] = 16'b1011001110111110;
		 mem[15] = 16'b1011011011010001;
		 mem[16] = 16'b0110000011000111;
		 mem[17] = 16'b0001100010100011;
		 mem[18] = 16'b1100101011110110;
		 mem[19] = 16'b1101110111100010;
		 mem[20] = 16'b0110101000011110;
		 mem[21] = 16'b0011101011010011;
		 mem[22] = 16'b1011101110000011;
		 mem[23] = 16'b0000001101011000;
		 mem[24] = 16'b0101110000101111;
		 mem[25] = 16'b1011101110111001;
		 mem[26] = 16'b1011010010111111;
		 mem[27] = 16'b1101100111101101;
		 mem[28] = 16'b0011111110101010;
		 mem[29] = 16'b1000111000110110;
		 mem[30] = 16'b1010010000100100;
		 mem[31] = 16'b1101110110001001;
		 mem[32] = 16'b1110101000001001;
		 mem[33] = 16'b0000110100001001;
		 mem[34] = 16'b1111100000000101;
		 mem[35] = 16'b0000010010010110;
		 mem[36] = 16'b0010011011010101;
		 mem[37] = 16'b1001110000101110;
		 mem[38] = 16'b1000100001100010;
		 mem[39] = 16'b0111100110001101;
		 mem[40] = 16'b1001000100100011;
		 mem[41] = 16'b0111101000110100;
		 mem[42] = 16'b0101111010110100;
		 mem[43] = 16'b0100101010111111;
		 mem[44] = 16'b0000001001110010;
		 mem[45] = 16'b1101001110001100;
		 mem[46] = 16'b0000111011011001;
		 mem[47] = 16'b1111000100101010;
		 mem[48] = 16'b1000111000101001;
		 mem[49] = 16'b0010000001011011;
		 mem[50] = 16'b0100010101101011;
		 mem[51] = 16'b0001100011100101;
		 mem[52] = 16'b1001011001111001;
		 mem[53] = 16'b1101001000101100;
		 mem[54] = 16'b1111111001111010;
		 mem[55] = 16'b0111100011111101;
		 mem[56] = 16'b0101010101001101;
		 mem[57] = 16'b0110110111001011;
		 mem[58] = 16'b1000010111000100;
		 mem[59] = 16'b1111001011000110;
		 mem[60] = 16'b0111100001100001;
		 mem[61] = 16'b1110101011011011;
		 mem[62] = 16'b1000011010101010;
		 mem[63] = 16'b0100010010100110;
		 mem[64] = 16'b0001100000111101;
		 mem[65] = 16'b0000000000010001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
