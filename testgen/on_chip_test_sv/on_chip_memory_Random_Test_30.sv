module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0010001110011110;
		 mem[1] = 16'b1001110000010000;
		 mem[2] = 16'b0001110110010111;
		 mem[3] = 16'b1101011111101101;
		 mem[4] = 16'b1101000101110101;
		 mem[5] = 16'b0101010010010000;
		 mem[6] = 16'b0000010010000111;
		 mem[7] = 16'b1001011001010010;
		 mem[8] = 16'b1100101000010110;
		 mem[9] = 16'b1101011110100100;
		 mem[10] = 16'b0110100101001001;
		 mem[11] = 16'b0011011111011100;
		 mem[12] = 16'b0010000010011010;
		 mem[13] = 16'b1011110001010010;
		 mem[14] = 16'b0000101001111001;
		 mem[15] = 16'b1010101101111000;
		 mem[16] = 16'b0100010001110011;
		 mem[17] = 16'b1110010011111110;
		 mem[18] = 16'b1011110010100111;
		 mem[19] = 16'b1010100001100000;
		 mem[20] = 16'b1111010010111100;
		 mem[21] = 16'b1001001111101111;
		 mem[22] = 16'b1010000010000100;
		 mem[23] = 16'b0001000011000001;
		 mem[24] = 16'b0100101110001111;
		 mem[25] = 16'b0001101101001110;
		 mem[26] = 16'b0011000010000111;
		 mem[27] = 16'b1011000100000101;
		 mem[28] = 16'b1100011001110010;
		 mem[29] = 16'b0111001001010000;
		 mem[30] = 16'b1110001110000010;
		 mem[31] = 16'b1001000001111010;
		 mem[32] = 16'b1000101001010001;
		 mem[33] = 16'b0001101010110101;
		 mem[34] = 16'b0010000100110011;
		 mem[35] = 16'b1110001000110000;
		 mem[36] = 16'b0001110001110111;
		 mem[37] = 16'b1111010001011111;
		 mem[38] = 16'b1010011110010110;
		 mem[39] = 16'b1101101111001001;
		 mem[40] = 16'b1011011010011010;
		 mem[41] = 16'b1111111001101101;
		 mem[42] = 16'b0000011101101111;
		 mem[43] = 16'b1000011010101100;
		 mem[44] = 16'b0011100011000011;
		 mem[45] = 16'b0110011101111101;
		 mem[46] = 16'b0111010101111110;
		 mem[47] = 16'b0011010010100111;
		 mem[48] = 16'b1111001111001101;
		 mem[49] = 16'b1001000111100111;
		 mem[50] = 16'b0100111011100100;
		 mem[51] = 16'b1111101100001010;
		 mem[52] = 16'b0011110000001100;
		 mem[53] = 16'b0110000110111011;
		 mem[54] = 16'b0110100000111110;
		 mem[55] = 16'b0111000110011111;
		 mem[56] = 16'b0000001001001011;
		 mem[57] = 16'b0110101000110001;
		 mem[58] = 16'b0001000000100110;
		 mem[59] = 16'b1010011110101011;
		 mem[60] = 16'b1101010101000110;
		 mem[61] = 16'b0010101011010011;
		 mem[62] = 16'b1011001100010010;
		 mem[63] = 16'b1010000011111000;
		 mem[64] = 16'b1100111010101000;
		 mem[65] = 16'b0000000000111100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
