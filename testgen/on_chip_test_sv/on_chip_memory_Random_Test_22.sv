module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1000110011000100;
		 mem[1] = 16'b1000110001011001;
		 mem[2] = 16'b1111000100101110;
		 mem[3] = 16'b1110110111001110;
		 mem[4] = 16'b0011111011110100;
		 mem[5] = 16'b1000100000101101;
		 mem[6] = 16'b0011111001101101;
		 mem[7] = 16'b0101011110010100;
		 mem[8] = 16'b0000100101000111;
		 mem[9] = 16'b1100101100100011;
		 mem[10] = 16'b1101111000110110;
		 mem[11] = 16'b0100001111010100;
		 mem[12] = 16'b1110101011110100;
		 mem[13] = 16'b1001011010000010;
		 mem[14] = 16'b1111101011000111;
		 mem[15] = 16'b1101000101110001;
		 mem[16] = 16'b1001111011100010;
		 mem[17] = 16'b0110000001111011;
		 mem[18] = 16'b1011000010101110;
		 mem[19] = 16'b0011000110110010;
		 mem[20] = 16'b1101110001000011;
		 mem[21] = 16'b0111001110111000;
		 mem[22] = 16'b0100000101111011;
		 mem[23] = 16'b1000000111011010;
		 mem[24] = 16'b0110010111000001;
		 mem[25] = 16'b1100110110101000;
		 mem[26] = 16'b0101111110001010;
		 mem[27] = 16'b1010110000011100;
		 mem[28] = 16'b1011110101101001;
		 mem[29] = 16'b0010011100010001;
		 mem[30] = 16'b1110101111011100;
		 mem[31] = 16'b0111000010111011;
		 mem[32] = 16'b0001000011001100;
		 mem[33] = 16'b0011111010111101;
		 mem[34] = 16'b1010101100111111;
		 mem[35] = 16'b0010110000100001;
		 mem[36] = 16'b1000010110000001;
		 mem[37] = 16'b0111000100100010;
		 mem[38] = 16'b1010010111110010;
		 mem[39] = 16'b0011111100011000;
		 mem[40] = 16'b1000111001101101;
		 mem[41] = 16'b0111000110001010;
		 mem[42] = 16'b1111011110000010;
		 mem[43] = 16'b1111011101101111;
		 mem[44] = 16'b0110001100100110;
		 mem[45] = 16'b0010000111100111;
		 mem[46] = 16'b1010100010101110;
		 mem[47] = 16'b1001010000101101;
		 mem[48] = 16'b1100111111110011;
		 mem[49] = 16'b0001001101100000;
		 mem[50] = 16'b0000001101110010;
		 mem[51] = 16'b0100000110111110;
		 mem[52] = 16'b0000000001101110;
		 mem[53] = 16'b0110101001101100;
		 mem[54] = 16'b0011011110111011;
		 mem[55] = 16'b1011010010001011;
		 mem[56] = 16'b1100101101010111;
		 mem[57] = 16'b1101100111000000;
		 mem[58] = 16'b1000011100000010;
		 mem[59] = 16'b0101111001101000;
		 mem[60] = 16'b1110000100111110;
		 mem[61] = 16'b1111000110111101;
		 mem[62] = 16'b1110001001111100;
		 mem[63] = 16'b0011000010101111;
		 mem[64] = 16'b0100011110001010;
		 mem[65] = 16'b0000000000110000;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
