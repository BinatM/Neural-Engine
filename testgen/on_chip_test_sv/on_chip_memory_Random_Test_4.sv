module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1111100001011100;
		 mem[1] = 16'b0110110111111011;
		 mem[2] = 16'b0010100001011000;
		 mem[3] = 16'b1101110110100001;
		 mem[4] = 16'b0011011001101010;
		 mem[5] = 16'b0001101011011110;
		 mem[6] = 16'b0011001110010111;
		 mem[7] = 16'b0011011000111111;
		 mem[8] = 16'b1110100100111010;
		 mem[9] = 16'b0111110010110001;
		 mem[10] = 16'b0111101101011110;
		 mem[11] = 16'b0101110000101101;
		 mem[12] = 16'b1010000010001010;
		 mem[13] = 16'b1111110101110110;
		 mem[14] = 16'b1110011101010011;
		 mem[15] = 16'b0011110101101101;
		 mem[16] = 16'b1000000011100101;
		 mem[17] = 16'b0110011010110111;
		 mem[18] = 16'b0001011010100110;
		 mem[19] = 16'b1000001110011101;
		 mem[20] = 16'b1111001110111100;
		 mem[21] = 16'b1001000010111101;
		 mem[22] = 16'b1110000010110111;
		 mem[23] = 16'b0110100110001111;
		 mem[24] = 16'b0100000000110101;
		 mem[25] = 16'b1100100110110110;
		 mem[26] = 16'b1111110101001010;
		 mem[27] = 16'b1100010101001110;
		 mem[28] = 16'b1010011100001101;
		 mem[29] = 16'b0101010000001010;
		 mem[30] = 16'b0010100101111010;
		 mem[31] = 16'b1001000101011111;
		 mem[32] = 16'b0011101110000100;
		 mem[33] = 16'b0001010010001011;
		 mem[34] = 16'b0101010011100101;
		 mem[35] = 16'b1010011100111001;
		 mem[36] = 16'b1010110111001100;
		 mem[37] = 16'b0010101100000011;
		 mem[38] = 16'b0010110000010101;
		 mem[39] = 16'b0101110011101000;
		 mem[40] = 16'b0011001111001000;
		 mem[41] = 16'b1010111110111001;
		 mem[42] = 16'b0101000110101101;
		 mem[43] = 16'b1011101100001010;
		 mem[44] = 16'b1111110100011101;
		 mem[45] = 16'b0011010100110101;
		 mem[46] = 16'b0010101111101000;
		 mem[47] = 16'b1101011000010000;
		 mem[48] = 16'b1011010101110010;
		 mem[49] = 16'b1001001101111110;
		 mem[50] = 16'b0011110010000100;
		 mem[51] = 16'b0110001110111100;
		 mem[52] = 16'b1010011111000011;
		 mem[53] = 16'b1010101000110111;
		 mem[54] = 16'b0110011101111111;
		 mem[55] = 16'b1101000010111001;
		 mem[56] = 16'b1000011000001001;
		 mem[57] = 16'b1111110100100010;
		 mem[58] = 16'b1000000000100000;
		 mem[59] = 16'b1110101101011011;
		 mem[60] = 16'b0111101000011111;
		 mem[61] = 16'b1100111011111100;
		 mem[62] = 16'b1010100011010011;
		 mem[63] = 16'b1001101111111010;
		 mem[64] = 16'b1010010010110100;
		 mem[65] = 16'b0000000000100110;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
