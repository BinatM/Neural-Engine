module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0010101110110010;
		 mem[1] = 16'b1000011101101101;
		 mem[2] = 16'b1101100111011101;
		 mem[3] = 16'b0101111001101100;
		 mem[4] = 16'b1000001100110101;
		 mem[5] = 16'b1001100101001011;
		 mem[6] = 16'b0100000100101101;
		 mem[7] = 16'b0000011010101111;
		 mem[8] = 16'b1110110011110110;
		 mem[9] = 16'b0110110101001000;
		 mem[10] = 16'b1100011101011001;
		 mem[11] = 16'b1110110011001100;
		 mem[12] = 16'b0010101110110011;
		 mem[13] = 16'b0000010001011011;
		 mem[14] = 16'b1111001110100111;
		 mem[15] = 16'b1110111001001011;
		 mem[16] = 16'b0010010100010100;
		 mem[17] = 16'b1111000001101010;
		 mem[18] = 16'b1001110010001100;
		 mem[19] = 16'b0110111011000111;
		 mem[20] = 16'b0101001001100111;
		 mem[21] = 16'b1110000100000001;
		 mem[22] = 16'b0110110101011001;
		 mem[23] = 16'b0000000110101001;
		 mem[24] = 16'b0010011101110010;
		 mem[25] = 16'b1001010011101110;
		 mem[26] = 16'b1001100011001101;
		 mem[27] = 16'b0010000100100001;
		 mem[28] = 16'b0010101111110110;
		 mem[29] = 16'b1000101011111001;
		 mem[30] = 16'b0101001111010110;
		 mem[31] = 16'b0001101010001011;
		 mem[32] = 16'b0011010001101001;
		 mem[33] = 16'b1010111000110001;
		 mem[34] = 16'b0110001011101001;
		 mem[35] = 16'b0000110011100010;
		 mem[36] = 16'b1001110111111010;
		 mem[37] = 16'b0101010011110011;
		 mem[38] = 16'b1011111011101001;
		 mem[39] = 16'b1011000000111100;
		 mem[40] = 16'b0111001111001000;
		 mem[41] = 16'b1001010110001111;
		 mem[42] = 16'b1001010010010000;
		 mem[43] = 16'b0010110110101111;
		 mem[44] = 16'b0110101010000000;
		 mem[45] = 16'b0101001010000001;
		 mem[46] = 16'b1110010010100011;
		 mem[47] = 16'b0101000010101111;
		 mem[48] = 16'b0001000100001110;
		 mem[49] = 16'b0111110100110011;
		 mem[50] = 16'b1111111101111110;
		 mem[51] = 16'b1011001111011110;
		 mem[52] = 16'b0000100111010110;
		 mem[53] = 16'b1111101111100011;
		 mem[54] = 16'b1000001100111100;
		 mem[55] = 16'b1100010010001000;
		 mem[56] = 16'b0011111000111000;
		 mem[57] = 16'b1101010110101011;
		 mem[58] = 16'b1110100011001100;
		 mem[59] = 16'b0110001100011101;
		 mem[60] = 16'b0010010011011110;
		 mem[61] = 16'b0000011100100101;
		 mem[62] = 16'b0111111001011110;
		 mem[63] = 16'b0000111001111000;
		 mem[64] = 16'b0001010110101110;
		 mem[65] = 16'b0000000000000111;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
