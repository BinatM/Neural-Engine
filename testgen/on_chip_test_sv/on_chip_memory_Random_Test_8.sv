module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1110101111101101;
		 mem[1] = 16'b1000010010100001;
		 mem[2] = 16'b0100100111111111;
		 mem[3] = 16'b1110010001111101;
		 mem[4] = 16'b1011010000110010;
		 mem[5] = 16'b0010001101101101;
		 mem[6] = 16'b0000011000010010;
		 mem[7] = 16'b0000100101000111;
		 mem[8] = 16'b1011100000101001;
		 mem[9] = 16'b1011000010001110;
		 mem[10] = 16'b0111111110100111;
		 mem[11] = 16'b0101010100011011;
		 mem[12] = 16'b0111001111110001;
		 mem[13] = 16'b1001000010110010;
		 mem[14] = 16'b0011111000101111;
		 mem[15] = 16'b1100011010101001;
		 mem[16] = 16'b1111000001101001;
		 mem[17] = 16'b1101111100101101;
		 mem[18] = 16'b1001111000110111;
		 mem[19] = 16'b1011101100101100;
		 mem[20] = 16'b1100001100000000;
		 mem[21] = 16'b0011011110111010;
		 mem[22] = 16'b0010100000110100;
		 mem[23] = 16'b0101101110011101;
		 mem[24] = 16'b0100110011101110;
		 mem[25] = 16'b1111110101000101;
		 mem[26] = 16'b0110101011100101;
		 mem[27] = 16'b0110001011111100;
		 mem[28] = 16'b0111111101010111;
		 mem[29] = 16'b1001100100101010;
		 mem[30] = 16'b1000011010011011;
		 mem[31] = 16'b0110001000000010;
		 mem[32] = 16'b0011001110001011;
		 mem[33] = 16'b1110001000011000;
		 mem[34] = 16'b0010110000000001;
		 mem[35] = 16'b1101101110100100;
		 mem[36] = 16'b0111010100011111;
		 mem[37] = 16'b0001100000101011;
		 mem[38] = 16'b1000011100100010;
		 mem[39] = 16'b1000001011000001;
		 mem[40] = 16'b1001100001011010;
		 mem[41] = 16'b0001011111010100;
		 mem[42] = 16'b0010000111100110;
		 mem[43] = 16'b1001010001101110;
		 mem[44] = 16'b0110010100110001;
		 mem[45] = 16'b1010001110111100;
		 mem[46] = 16'b1101010101101011;
		 mem[47] = 16'b1100110011100000;
		 mem[48] = 16'b0111001100111001;
		 mem[49] = 16'b0011111110110000;
		 mem[50] = 16'b1011000000110100;
		 mem[51] = 16'b1011011111101110;
		 mem[52] = 16'b1000110010001010;
		 mem[53] = 16'b0000100101011111;
		 mem[54] = 16'b0010101000101000;
		 mem[55] = 16'b0001111001001100;
		 mem[56] = 16'b1111001011000111;
		 mem[57] = 16'b1010110011100111;
		 mem[58] = 16'b0000000110010100;
		 mem[59] = 16'b1101111001000101;
		 mem[60] = 16'b0010111011000001;
		 mem[61] = 16'b1011110010001101;
		 mem[62] = 16'b0111001001101011;
		 mem[63] = 16'b1001011000111101;
		 mem[64] = 16'b1110010000111001;
		 mem[65] = 16'b0000000000011100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
