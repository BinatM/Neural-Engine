module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1110000101101010;
		 mem[1] = 16'b0111001000000101;
		 mem[2] = 16'b0001010100111000;
		 mem[3] = 16'b1101110010101011;
		 mem[4] = 16'b1100000011000000;
		 mem[5] = 16'b1110111110000110;
		 mem[6] = 16'b1011001001100100;
		 mem[7] = 16'b1100000101101000;
		 mem[8] = 16'b1111010111100100;
		 mem[9] = 16'b1001000111011100;
		 mem[10] = 16'b1101001101000011;
		 mem[11] = 16'b0001011110111101;
		 mem[12] = 16'b0001010010101000;
		 mem[13] = 16'b1101000100001010;
		 mem[14] = 16'b1011001011001110;
		 mem[15] = 16'b1010010000101000;
		 mem[16] = 16'b1001000000011111;
		 mem[17] = 16'b1011111000010100;
		 mem[18] = 16'b1011111010011010;
		 mem[19] = 16'b0011000100000001;
		 mem[20] = 16'b0001110110000000;
		 mem[21] = 16'b1000111101010000;
		 mem[22] = 16'b1110100111011111;
		 mem[23] = 16'b1000110010101101;
		 mem[24] = 16'b0000011101110011;
		 mem[25] = 16'b0110111101001000;
		 mem[26] = 16'b0111101101000110;
		 mem[27] = 16'b0011001001000111;
		 mem[28] = 16'b1110101001010111;
		 mem[29] = 16'b1110000110111111;
		 mem[30] = 16'b1111100101110001;
		 mem[31] = 16'b1010011000101010;
		 mem[32] = 16'b0000100110001001;
		 mem[33] = 16'b1011101110000100;
		 mem[34] = 16'b0110111011110110;
		 mem[35] = 16'b1111011101001001;
		 mem[36] = 16'b1100011011111000;
		 mem[37] = 16'b1010110111110011;
		 mem[38] = 16'b0101101111010101;
		 mem[39] = 16'b1000101110000100;
		 mem[40] = 16'b1111000010100001;
		 mem[41] = 16'b1100011011110100;
		 mem[42] = 16'b0100011010111010;
		 mem[43] = 16'b0100100100111011;
		 mem[44] = 16'b1000110100100010;
		 mem[45] = 16'b0011101011001011;
		 mem[46] = 16'b1110111110010001;
		 mem[47] = 16'b1001100001100011;
		 mem[48] = 16'b1100011001101001;
		 mem[49] = 16'b0101001011101011;
		 mem[50] = 16'b0100011010101100;
		 mem[51] = 16'b1111000000100001;
		 mem[52] = 16'b1110010000110100;
		 mem[53] = 16'b1001000000000100;
		 mem[54] = 16'b1101000111110110;
		 mem[55] = 16'b1110110100011100;
		 mem[56] = 16'b0011011000101010;
		 mem[57] = 16'b1010101100001000;
		 mem[58] = 16'b0000000001010101;
		 mem[59] = 16'b1010110110100101;
		 mem[60] = 16'b0110110110111101;
		 mem[61] = 16'b1001011000101111;
		 mem[62] = 16'b0001111101000000;
		 mem[63] = 16'b1010110100110111;
		 mem[64] = 16'b0011110101001100;
		 mem[65] = 16'b0000000000111001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
