module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1110100100000011;
		 mem[1] = 16'b0001010110000011;
		 mem[2] = 16'b1100100011100011;
		 mem[3] = 16'b0111100101110001;
		 mem[4] = 16'b0011011001100000;
		 mem[5] = 16'b0000110000111001;
		 mem[6] = 16'b1000100011110011;
		 mem[7] = 16'b1010100010111101;
		 mem[8] = 16'b1010111001010101;
		 mem[9] = 16'b1001111101010010;
		 mem[10] = 16'b0101001101001000;
		 mem[11] = 16'b1000110110111000;
		 mem[12] = 16'b0111110000101101;
		 mem[13] = 16'b1000101011010100;
		 mem[14] = 16'b1010110101011110;
		 mem[15] = 16'b1111011001000010;
		 mem[16] = 16'b1000001001100000;
		 mem[17] = 16'b0100110111011111;
		 mem[18] = 16'b0110000001111111;
		 mem[19] = 16'b0101010111101110;
		 mem[20] = 16'b0111011011001111;
		 mem[21] = 16'b1100000001011110;
		 mem[22] = 16'b1000000101010100;
		 mem[23] = 16'b1001011000011011;
		 mem[24] = 16'b0110001110101101;
		 mem[25] = 16'b1000001011111100;
		 mem[26] = 16'b1010100000100001;
		 mem[27] = 16'b0010111100100010;
		 mem[28] = 16'b0010000011101111;
		 mem[29] = 16'b1111011111100010;
		 mem[30] = 16'b0100001101111010;
		 mem[31] = 16'b1000111100011011;
		 mem[32] = 16'b0011110011000110;
		 mem[33] = 16'b1011011110010001;
		 mem[34] = 16'b0011001011111010;
		 mem[35] = 16'b0010110111011111;
		 mem[36] = 16'b0110010001001100;
		 mem[37] = 16'b0001110110011101;
		 mem[38] = 16'b0010000000100011;
		 mem[39] = 16'b1000010101111010;
		 mem[40] = 16'b0111011100011001;
		 mem[41] = 16'b0001000001011100;
		 mem[42] = 16'b0011111100001010;
		 mem[43] = 16'b0000101010110110;
		 mem[44] = 16'b0010011001100101;
		 mem[45] = 16'b0101001011111001;
		 mem[46] = 16'b1000000101101100;
		 mem[47] = 16'b0010010011110000;
		 mem[48] = 16'b1001100011010010;
		 mem[49] = 16'b1011110010001010;
		 mem[50] = 16'b1010110010011011;
		 mem[51] = 16'b1110000000111001;
		 mem[52] = 16'b0010111010101100;
		 mem[53] = 16'b1110001110100111;
		 mem[54] = 16'b0010011011010011;
		 mem[55] = 16'b1001101110100111;
		 mem[56] = 16'b1011100100101111;
		 mem[57] = 16'b1010111101101100;
		 mem[58] = 16'b1000001011111100;
		 mem[59] = 16'b0001010101111001;
		 mem[60] = 16'b0001100100111110;
		 mem[61] = 16'b0000110000111111;
		 mem[62] = 16'b0111100110010110;
		 mem[63] = 16'b1010000110111010;
		 mem[64] = 16'b0000101010100101;
		 mem[65] = 16'b0000000000011110;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
