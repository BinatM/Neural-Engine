module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1110001100110001;
		 mem[1] = 16'b0100110011110101;
		 mem[2] = 16'b0110010011110100;
		 mem[3] = 16'b0110001010111100;
		 mem[4] = 16'b0111010111100000;
		 mem[5] = 16'b1110011010111010;
		 mem[6] = 16'b1111000011011110;
		 mem[7] = 16'b1101010001010100;
		 mem[8] = 16'b0011001100010011;
		 mem[9] = 16'b1010101100001100;
		 mem[10] = 16'b1111001110011011;
		 mem[11] = 16'b0010110000000100;
		 mem[12] = 16'b0110111001101001;
		 mem[13] = 16'b0110100011110010;
		 mem[14] = 16'b0001100110001001;
		 mem[15] = 16'b0011001100111111;
		 mem[16] = 16'b1001100101010010;
		 mem[17] = 16'b0100001000110100;
		 mem[18] = 16'b0000101101100011;
		 mem[19] = 16'b1100110110101101;
		 mem[20] = 16'b0010100100010001;
		 mem[21] = 16'b0110000101011010;
		 mem[22] = 16'b1110110100000101;
		 mem[23] = 16'b0101111001001010;
		 mem[24] = 16'b1001010010001011;
		 mem[25] = 16'b1010101110111011;
		 mem[26] = 16'b0001110001110000;
		 mem[27] = 16'b0001101110000101;
		 mem[28] = 16'b0100010101010101;
		 mem[29] = 16'b1000100000010010;
		 mem[30] = 16'b1111111000001011;
		 mem[31] = 16'b0001110001010000;
		 mem[32] = 16'b1100111111000110;
		 mem[33] = 16'b1010110101000100;
		 mem[34] = 16'b0001010000100100;
		 mem[35] = 16'b0111001000101100;
		 mem[36] = 16'b0101111000110010;
		 mem[37] = 16'b0001111001110101;
		 mem[38] = 16'b0011100011001001;
		 mem[39] = 16'b0100110111011010;
		 mem[40] = 16'b0101100001111100;
		 mem[41] = 16'b0100100101101000;
		 mem[42] = 16'b1100100100011001;
		 mem[43] = 16'b0110111001100011;
		 mem[44] = 16'b0101110111001011;
		 mem[45] = 16'b1001100110101010;
		 mem[46] = 16'b1001011000000101;
		 mem[47] = 16'b0100101110000001;
		 mem[48] = 16'b1111111111001101;
		 mem[49] = 16'b1110001000001011;
		 mem[50] = 16'b0000011000100110;
		 mem[51] = 16'b0000010101010001;
		 mem[52] = 16'b0101100010100011;
		 mem[53] = 16'b0010000110101010;
		 mem[54] = 16'b0001001000011101;
		 mem[55] = 16'b1010101111101100;
		 mem[56] = 16'b0111011011010011;
		 mem[57] = 16'b0100110101100100;
		 mem[58] = 16'b1010111101101101;
		 mem[59] = 16'b1110010010011000;
		 mem[60] = 16'b0000011000110000;
		 mem[61] = 16'b0111011110011010;
		 mem[62] = 16'b0010101111101011;
		 mem[63] = 16'b0000101000001100;
		 mem[64] = 16'b0111101101010110;
		 mem[65] = 16'b0000000000011100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
