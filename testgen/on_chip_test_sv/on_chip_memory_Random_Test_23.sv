module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1111101000101001;
		 mem[1] = 16'b0000010011110100;
		 mem[2] = 16'b0010101010110100;
		 mem[3] = 16'b1101111000100100;
		 mem[4] = 16'b0000101000010000;
		 mem[5] = 16'b0110000001010101;
		 mem[6] = 16'b1111011111001101;
		 mem[7] = 16'b0111101111001110;
		 mem[8] = 16'b0010110001001111;
		 mem[9] = 16'b1110000001000100;
		 mem[10] = 16'b1011000111110100;
		 mem[11] = 16'b0000101000011010;
		 mem[12] = 16'b1111010001111111;
		 mem[13] = 16'b0001110000100111;
		 mem[14] = 16'b0111110101011101;
		 mem[15] = 16'b1010000011010110;
		 mem[16] = 16'b1100111111001100;
		 mem[17] = 16'b0011101101011011;
		 mem[18] = 16'b1011011011100111;
		 mem[19] = 16'b1011011110101101;
		 mem[20] = 16'b0110010110010100;
		 mem[21] = 16'b0110000100101000;
		 mem[22] = 16'b0001000000111110;
		 mem[23] = 16'b0000110010001011;
		 mem[24] = 16'b0111101010001010;
		 mem[25] = 16'b1101011110111010;
		 mem[26] = 16'b0100001011010010;
		 mem[27] = 16'b0110001111001110;
		 mem[28] = 16'b0101010100011111;
		 mem[29] = 16'b0000100010000110;
		 mem[30] = 16'b1101101011001100;
		 mem[31] = 16'b0000010101010000;
		 mem[32] = 16'b0000010110100101;
		 mem[33] = 16'b0001001010100100;
		 mem[34] = 16'b1101100100000001;
		 mem[35] = 16'b0001111111001011;
		 mem[36] = 16'b0011110111100001;
		 mem[37] = 16'b1010111111000011;
		 mem[38] = 16'b0110011000001110;
		 mem[39] = 16'b0111111110010110;
		 mem[40] = 16'b0101001101010110;
		 mem[41] = 16'b0010011100110001;
		 mem[42] = 16'b1101110110000010;
		 mem[43] = 16'b1010000011111100;
		 mem[44] = 16'b1010000001001010;
		 mem[45] = 16'b0101000111010111;
		 mem[46] = 16'b0000111010010011;
		 mem[47] = 16'b1011101101011100;
		 mem[48] = 16'b1100111000111100;
		 mem[49] = 16'b1010011100110110;
		 mem[50] = 16'b0010011001000011;
		 mem[51] = 16'b1111011101101110;
		 mem[52] = 16'b1001010110011101;
		 mem[53] = 16'b1110010111001111;
		 mem[54] = 16'b0000011101111100;
		 mem[55] = 16'b0001011101011001;
		 mem[56] = 16'b1001110001111011;
		 mem[57] = 16'b1011110011110010;
		 mem[58] = 16'b0001101111001100;
		 mem[59] = 16'b1101010101001011;
		 mem[60] = 16'b0001001010001110;
		 mem[61] = 16'b0111101010001101;
		 mem[62] = 16'b0101100010110001;
		 mem[63] = 16'b0111011110001100;
		 mem[64] = 16'b0101110001100001;
		 mem[65] = 16'b0000000000110000;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
