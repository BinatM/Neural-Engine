module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1000001101110010;
		 mem[1] = 16'b0100111100110101;
		 mem[2] = 16'b1010011011101110;
		 mem[3] = 16'b1011011011010111;
		 mem[4] = 16'b1000010001000110;
		 mem[5] = 16'b1111111111000101;
		 mem[6] = 16'b0011111110011111;
		 mem[7] = 16'b1000001110011111;
		 mem[8] = 16'b1000000000001110;
		 mem[9] = 16'b0111010101011101;
		 mem[10] = 16'b0011010011100110;
		 mem[11] = 16'b0101111010101001;
		 mem[12] = 16'b0011100101001011;
		 mem[13] = 16'b0110110001111000;
		 mem[14] = 16'b1101011100000000;
		 mem[15] = 16'b1010100100010010;
		 mem[16] = 16'b1011010100010010;
		 mem[17] = 16'b0010000110111001;
		 mem[18] = 16'b0100111111110011;
		 mem[19] = 16'b1001100000111011;
		 mem[20] = 16'b1001111011000101;
		 mem[21] = 16'b0111010011010000;
		 mem[22] = 16'b0000010101111111;
		 mem[23] = 16'b0010100100110101;
		 mem[24] = 16'b0000100000100000;
		 mem[25] = 16'b0010111000010010;
		 mem[26] = 16'b1111100010011100;
		 mem[27] = 16'b0011001110111100;
		 mem[28] = 16'b0110001001110100;
		 mem[29] = 16'b1001001101011101;
		 mem[30] = 16'b0101011101111001;
		 mem[31] = 16'b1101100100001110;
		 mem[32] = 16'b0010111010011101;
		 mem[33] = 16'b1110100110000001;
		 mem[34] = 16'b1111101011000011;
		 mem[35] = 16'b0000100101101000;
		 mem[36] = 16'b0001110111010010;
		 mem[37] = 16'b1101101000011100;
		 mem[38] = 16'b1100010100001001;
		 mem[39] = 16'b1010011011011010;
		 mem[40] = 16'b1011010110110101;
		 mem[41] = 16'b1101100111000100;
		 mem[42] = 16'b0010101110001101;
		 mem[43] = 16'b0111100100111111;
		 mem[44] = 16'b0010000100110100;
		 mem[45] = 16'b1111110100100111;
		 mem[46] = 16'b0101010011011001;
		 mem[47] = 16'b1011001101101011;
		 mem[48] = 16'b1101110011101000;
		 mem[49] = 16'b0010001110111101;
		 mem[50] = 16'b0000010101111010;
		 mem[51] = 16'b0101101000100011;
		 mem[52] = 16'b0111100111101110;
		 mem[53] = 16'b1010110111100101;
		 mem[54] = 16'b0111110111011010;
		 mem[55] = 16'b0011010100010010;
		 mem[56] = 16'b1000111110001000;
		 mem[57] = 16'b1010001011100110;
		 mem[58] = 16'b0110010111001100;
		 mem[59] = 16'b0001111000101110;
		 mem[60] = 16'b0001011111100111;
		 mem[61] = 16'b0011010100111100;
		 mem[62] = 16'b0100101110011010;
		 mem[63] = 16'b0110100111011001;
		 mem[64] = 16'b0010011110101010;
		 mem[65] = 16'b0000000000011011;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
