module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0101111110011011;
		 mem[1] = 16'b0111001111110000;
		 mem[2] = 16'b1010111001000010;
		 mem[3] = 16'b0000110111010001;
		 mem[4] = 16'b0111111010011111;
		 mem[5] = 16'b0000001000101110;
		 mem[6] = 16'b1111010100010001;
		 mem[7] = 16'b0011110110001011;
		 mem[8] = 16'b0100110110010010;
		 mem[9] = 16'b1111001110101000;
		 mem[10] = 16'b0010100000011011;
		 mem[11] = 16'b1110010011010101;
		 mem[12] = 16'b0011011100100000;
		 mem[13] = 16'b0000000011000100;
		 mem[14] = 16'b1000011000001100;
		 mem[15] = 16'b0000001100101001;
		 mem[16] = 16'b1001010011111110;
		 mem[17] = 16'b1111011100111000;
		 mem[18] = 16'b0110000001100010;
		 mem[19] = 16'b1100011100000001;
		 mem[20] = 16'b1110100001010110;
		 mem[21] = 16'b1101000111010000;
		 mem[22] = 16'b1100111101111111;
		 mem[23] = 16'b0111001100110100;
		 mem[24] = 16'b0011001000110001;
		 mem[25] = 16'b1000001001010011;
		 mem[26] = 16'b0001010101011011;
		 mem[27] = 16'b0111111011100011;
		 mem[28] = 16'b0111001111001111;
		 mem[29] = 16'b1110001100011100;
		 mem[30] = 16'b1111111111001111;
		 mem[31] = 16'b1111101110001011;
		 mem[32] = 16'b1111000010111011;
		 mem[33] = 16'b1101011101110110;
		 mem[34] = 16'b1000111100011100;
		 mem[35] = 16'b1101110111101100;
		 mem[36] = 16'b0100111001010111;
		 mem[37] = 16'b1111001001011010;
		 mem[38] = 16'b1010101000011000;
		 mem[39] = 16'b1100001111101011;
		 mem[40] = 16'b0010101111101101;
		 mem[41] = 16'b1111111110101101;
		 mem[42] = 16'b0100000101011100;
		 mem[43] = 16'b0010111110001001;
		 mem[44] = 16'b0000110110110000;
		 mem[45] = 16'b0101010011110001;
		 mem[46] = 16'b1001000101001001;
		 mem[47] = 16'b0100100000000011;
		 mem[48] = 16'b1001010010100011;
		 mem[49] = 16'b1111001110000000;
		 mem[50] = 16'b0101000100011000;
		 mem[51] = 16'b0010010000010101;
		 mem[52] = 16'b1011000100000010;
		 mem[53] = 16'b1001001101000110;
		 mem[54] = 16'b0010001101011100;
		 mem[55] = 16'b0101100100001000;
		 mem[56] = 16'b1110111110111101;
		 mem[57] = 16'b1000101100000001;
		 mem[58] = 16'b0100100101111101;
		 mem[59] = 16'b0110101000011110;
		 mem[60] = 16'b0111111111011010;
		 mem[61] = 16'b0010101111010101;
		 mem[62] = 16'b0100010111001010;
		 mem[63] = 16'b1100101101011001;
		 mem[64] = 16'b1001110000100101;
		 mem[65] = 16'b0000000000110100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
