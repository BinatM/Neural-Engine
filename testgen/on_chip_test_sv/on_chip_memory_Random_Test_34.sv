module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1010000011101000;
		 mem[1] = 16'b0010001010101010;
		 mem[2] = 16'b1100010011000100;
		 mem[3] = 16'b1001100011100101;
		 mem[4] = 16'b1111110111011111;
		 mem[5] = 16'b1110110010001101;
		 mem[6] = 16'b1001111111010000;
		 mem[7] = 16'b0001001111100000;
		 mem[8] = 16'b1110101000101110;
		 mem[9] = 16'b0011011100011100;
		 mem[10] = 16'b1101100000000101;
		 mem[11] = 16'b0001000000111001;
		 mem[12] = 16'b0001011110011100;
		 mem[13] = 16'b1010111101101010;
		 mem[14] = 16'b0111111011101010;
		 mem[15] = 16'b1001111110010110;
		 mem[16] = 16'b1010110111100010;
		 mem[17] = 16'b1110011011000011;
		 mem[18] = 16'b0100001000000111;
		 mem[19] = 16'b0110111001100001;
		 mem[20] = 16'b0111000110111010;
		 mem[21] = 16'b1011110000011111;
		 mem[22] = 16'b1111100010011011;
		 mem[23] = 16'b0111101100110110;
		 mem[24] = 16'b0001011010001100;
		 mem[25] = 16'b0001100101101111;
		 mem[26] = 16'b0011100001000011;
		 mem[27] = 16'b0000111000000001;
		 mem[28] = 16'b1001000000000110;
		 mem[29] = 16'b1001101111001000;
		 mem[30] = 16'b0011111111011001;
		 mem[31] = 16'b1001011011010000;
		 mem[32] = 16'b0000101100101101;
		 mem[33] = 16'b0001101000011100;
		 mem[34] = 16'b0111010010110001;
		 mem[35] = 16'b1011001001111111;
		 mem[36] = 16'b1000000010100110;
		 mem[37] = 16'b0110100110010111;
		 mem[38] = 16'b1111100100010001;
		 mem[39] = 16'b0010101101010011;
		 mem[40] = 16'b0100100010001011;
		 mem[41] = 16'b1000111011111101;
		 mem[42] = 16'b1000110111011101;
		 mem[43] = 16'b0000100100000000;
		 mem[44] = 16'b1011101100100000;
		 mem[45] = 16'b1000100001111000;
		 mem[46] = 16'b0010101100001111;
		 mem[47] = 16'b0110010010010100;
		 mem[48] = 16'b0110000011011010;
		 mem[49] = 16'b1101101000010101;
		 mem[50] = 16'b0111010101101111;
		 mem[51] = 16'b1111011111011110;
		 mem[52] = 16'b0111011001011001;
		 mem[53] = 16'b1000000000100000;
		 mem[54] = 16'b1000011100011010;
		 mem[55] = 16'b1011101111110101;
		 mem[56] = 16'b0010010110001010;
		 mem[57] = 16'b1000001111110111;
		 mem[58] = 16'b0110010000110110;
		 mem[59] = 16'b1100001000011101;
		 mem[60] = 16'b1111001111101101;
		 mem[61] = 16'b0000111111000010;
		 mem[62] = 16'b0110000001011100;
		 mem[63] = 16'b1011010011000100;
		 mem[64] = 16'b0111101100101001;
		 mem[65] = 16'b0000000000110100;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
