module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0110011110000100;
		 mem[1] = 16'b1000000011011111;
		 mem[2] = 16'b0011101000010110;
		 mem[3] = 16'b1110010101100011;
		 mem[4] = 16'b1100100010101010;
		 mem[5] = 16'b0011100111001100;
		 mem[6] = 16'b0111101100100011;
		 mem[7] = 16'b1101001110111100;
		 mem[8] = 16'b0001001111000011;
		 mem[9] = 16'b1110111111010000;
		 mem[10] = 16'b1001100111000100;
		 mem[11] = 16'b0000111000110100;
		 mem[12] = 16'b1111111010010011;
		 mem[13] = 16'b1111110101110111;
		 mem[14] = 16'b0111000101000001;
		 mem[15] = 16'b1110001011010110;
		 mem[16] = 16'b0111001100011100;
		 mem[17] = 16'b1000110011001110;
		 mem[18] = 16'b0001010000101110;
		 mem[19] = 16'b0000010000100111;
		 mem[20] = 16'b0100101111101111;
		 mem[21] = 16'b0110011011110101;
		 mem[22] = 16'b1011001100010011;
		 mem[23] = 16'b0001100100100111;
		 mem[24] = 16'b0100100110111001;
		 mem[25] = 16'b0100101111010010;
		 mem[26] = 16'b1101000000111100;
		 mem[27] = 16'b0010010011111110;
		 mem[28] = 16'b0100011000010010;
		 mem[29] = 16'b0010101100101010;
		 mem[30] = 16'b0010001001010011;
		 mem[31] = 16'b0110110110001110;
		 mem[32] = 16'b0100110001010110;
		 mem[33] = 16'b0101001011000001;
		 mem[34] = 16'b0111111001000000;
		 mem[35] = 16'b1011110100110011;
		 mem[36] = 16'b0000111011000101;
		 mem[37] = 16'b0001010101000001;
		 mem[38] = 16'b1100000110110111;
		 mem[39] = 16'b0011010101111110;
		 mem[40] = 16'b1010101101110001;
		 mem[41] = 16'b0010001111001101;
		 mem[42] = 16'b1100000010101100;
		 mem[43] = 16'b1011000011011001;
		 mem[44] = 16'b0011010011111000;
		 mem[45] = 16'b1001110001000110;
		 mem[46] = 16'b0101000011011101;
		 mem[47] = 16'b1101100000011011;
		 mem[48] = 16'b1010001101101111;
		 mem[49] = 16'b1101110110111001;
		 mem[50] = 16'b0011110101111100;
		 mem[51] = 16'b0101110101011101;
		 mem[52] = 16'b0000010100000111;
		 mem[53] = 16'b0101100111101010;
		 mem[54] = 16'b0111100010001010;
		 mem[55] = 16'b0000001010110110;
		 mem[56] = 16'b1110001101010010;
		 mem[57] = 16'b1110111011100000;
		 mem[58] = 16'b1010111110011101;
		 mem[59] = 16'b0011111101011011;
		 mem[60] = 16'b0011101000010011;
		 mem[61] = 16'b1010011010010101;
		 mem[62] = 16'b0110011101010010;
		 mem[63] = 16'b1111111010100010;
		 mem[64] = 16'b1100100000100111;
		 mem[65] = 16'b0000000000100001;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
