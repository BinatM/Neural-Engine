module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b0111001011010100;
		 mem[1] = 16'b0100001010000110;
		 mem[2] = 16'b1010001101111111;
		 mem[3] = 16'b0101111001001001;
		 mem[4] = 16'b1011111100100110;
		 mem[5] = 16'b1000110010111010;
		 mem[6] = 16'b1011100111110000;
		 mem[7] = 16'b0111101110011010;
		 mem[8] = 16'b1101100001000001;
		 mem[9] = 16'b0011001100001111;
		 mem[10] = 16'b1011101011111110;
		 mem[11] = 16'b1111010100000001;
		 mem[12] = 16'b1111001110111001;
		 mem[13] = 16'b0000110000101110;
		 mem[14] = 16'b1001010010110010;
		 mem[15] = 16'b1011110101010010;
		 mem[16] = 16'b1011011001110101;
		 mem[17] = 16'b0010000001001010;
		 mem[18] = 16'b1011101101101110;
		 mem[19] = 16'b0000001011101110;
		 mem[20] = 16'b0011100100011101;
		 mem[21] = 16'b0001101010111111;
		 mem[22] = 16'b1101010110101100;
		 mem[23] = 16'b1110111001111001;
		 mem[24] = 16'b0011010000011001;
		 mem[25] = 16'b1001101100101101;
		 mem[26] = 16'b0110110111110011;
		 mem[27] = 16'b1000100000100001;
		 mem[28] = 16'b1000000100011100;
		 mem[29] = 16'b0010000100011001;
		 mem[30] = 16'b0101001010110100;
		 mem[31] = 16'b1010001110100011;
		 mem[32] = 16'b0001010001010100;
		 mem[33] = 16'b1011111010010110;
		 mem[34] = 16'b1110011000010011;
		 mem[35] = 16'b0010110100101000;
		 mem[36] = 16'b0110110100110011;
		 mem[37] = 16'b0010100001110111;
		 mem[38] = 16'b0111001101011001;
		 mem[39] = 16'b1000001111011111;
		 mem[40] = 16'b1010111000110001;
		 mem[41] = 16'b0101110110001010;
		 mem[42] = 16'b0101001100011011;
		 mem[43] = 16'b0101111011101011;
		 mem[44] = 16'b0110010000010101;
		 mem[45] = 16'b0011110100111011;
		 mem[46] = 16'b1010011110110011;
		 mem[47] = 16'b1110100101001010;
		 mem[48] = 16'b1111101010010001;
		 mem[49] = 16'b0000101001001010;
		 mem[50] = 16'b0010100110010010;
		 mem[51] = 16'b1001110101010011;
		 mem[52] = 16'b0010111111000001;
		 mem[53] = 16'b1101111111111010;
		 mem[54] = 16'b1010111001101100;
		 mem[55] = 16'b0001101110100001;
		 mem[56] = 16'b1010001111100100;
		 mem[57] = 16'b0001001101111001;
		 mem[58] = 16'b0001001001110111;
		 mem[59] = 16'b0111011000100010;
		 mem[60] = 16'b0101111100110011;
		 mem[61] = 16'b0111010001101111;
		 mem[62] = 16'b0010011000110001;
		 mem[63] = 16'b1101111111100000;
		 mem[64] = 16'b1110111111100000;
		 mem[65] = 16'b0000000000001010;
		 expected_reg = 1'b1;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
