module on_chip_memory #(
    parameter ADDR_WIDTH = 7,
    parameter DATA_WIDTH = 16,
    parameter LOAD_DEPTH = 66
)(
    input  wire                     clk,
    input  wire                     reset_n,
    input  wire                     rd_en,
    input  wire [ADDR_WIDTH-1:0]    address_in,
    output reg  [DATA_WIDTH-1:0]              data_out,
    output reg                      expected_out
);

    reg [DATA_WIDTH-1:0] mem [0:LOAD_DEPTH-1];
    reg expected_reg;

    initial begin
		 mem[0] = 16'b1111000010111111;
		 mem[1] = 16'b1111101101110100;
		 mem[2] = 16'b0011100010001111;
		 mem[3] = 16'b1001100111100000;
		 mem[4] = 16'b1100000000001011;
		 mem[5] = 16'b1110001101100110;
		 mem[6] = 16'b1010000011011010;
		 mem[7] = 16'b0000011110100011;
		 mem[8] = 16'b0101000110111010;
		 mem[9] = 16'b0111100011001001;
		 mem[10] = 16'b0010011110101000;
		 mem[11] = 16'b0100101101100111;
		 mem[12] = 16'b0111101111000110;
		 mem[13] = 16'b0111010101110001;
		 mem[14] = 16'b1000001111001100;
		 mem[15] = 16'b1101001001000001;
		 mem[16] = 16'b1000010100000011;
		 mem[17] = 16'b1011010000100111;
		 mem[18] = 16'b0100111111001100;
		 mem[19] = 16'b1011000011000110;
		 mem[20] = 16'b0110110001100101;
		 mem[21] = 16'b1000000010011110;
		 mem[22] = 16'b0000000001101100;
		 mem[23] = 16'b0000110111001000;
		 mem[24] = 16'b0000010000010011;
		 mem[25] = 16'b1110011010111011;
		 mem[26] = 16'b0101111111011000;
		 mem[27] = 16'b0110010010000000;
		 mem[28] = 16'b1000000000100011;
		 mem[29] = 16'b0111011011000011;
		 mem[30] = 16'b0111000101000100;
		 mem[31] = 16'b1101110011010010;
		 mem[32] = 16'b1010011110000110;
		 mem[33] = 16'b1010111001101111;
		 mem[34] = 16'b0101100101101111;
		 mem[35] = 16'b0110010111011000;
		 mem[36] = 16'b1001001011001110;
		 mem[37] = 16'b1101111001111010;
		 mem[38] = 16'b0100000111011111;
		 mem[39] = 16'b1110000100010111;
		 mem[40] = 16'b1110001000100101;
		 mem[41] = 16'b0001100101000011;
		 mem[42] = 16'b1001101110100011;
		 mem[43] = 16'b1101000101001011;
		 mem[44] = 16'b0001000101110000;
		 mem[45] = 16'b1100011101100100;
		 mem[46] = 16'b1000101001011101;
		 mem[47] = 16'b1101001001000001;
		 mem[48] = 16'b0110101111110001;
		 mem[49] = 16'b1100010100000011;
		 mem[50] = 16'b1010011100010010;
		 mem[51] = 16'b1011001010101010;
		 mem[52] = 16'b0110001010101110;
		 mem[53] = 16'b1000001011011110;
		 mem[54] = 16'b0101111000100110;
		 mem[55] = 16'b1111001101100001;
		 mem[56] = 16'b0011111000100011;
		 mem[57] = 16'b1000101000011111;
		 mem[58] = 16'b0011100110100011;
		 mem[59] = 16'b0000000010101111;
		 mem[60] = 16'b0001101011111001;
		 mem[61] = 16'b1100110010000100;
		 mem[62] = 16'b1111111000001011;
		 mem[63] = 16'b1011000101011010;
		 mem[64] = 16'b0110000010010100;
		 mem[65] = 16'b0000000000011101;
		 expected_reg = 1'b0;
    end

    always_ff @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            data_out     <= 16'b0;
            expected_out <= 1'b0;
        end else begin
            if (rd_en) begin
                data_out <= mem[address_in];
            end
            expected_out <= expected_reg;
        end
    end

endmodule
